//! Generated behavioral tests (FR-7.8, VR-4).
//!
//! One runnable `GeneratedTests.java` — a per-union round-trip (known-tag
//! dispatch, discriminator survival on re-serialize, open-union unknown
//! retention / closed-union rejection) plus the tri-state (D-110) and date/time
//! serialization checks, all against the real generated codec. The Java analogue
//! of the Rust (D-156) and TypeScript (D-166) behavioral-test slices — but with
//! no test framework: it runs as a plain `main` that exits non-zero on the first
//! failure (like the existing `java`-executed round-trip gate), so the backend
//! gate can compile and *run* it. Deterministic, like all output (FR-6.2).

use std::fmt::Write as _;

use gantry_sema::Analysis;

use crate::GeneratedFile;
use crate::models::{UnionTestRow, tristate_test_target, union_test_rows};

/// The test class's repo-relative path (the Maven test source root).
const TEST_PATH: &str = "src/test/java/com/box/sdk/GeneratedTests.java";
/// The placeholder tag no real variant uses — exercises the unknown path.
const UNKNOWN_TAG: &str = "__gantry_unknown__";

/// Generate the runnable behavioral-test class.
pub fn generate_tests(analysis: &Analysis<'_>) -> Vec<GeneratedFile> {
    let program = analysis.program;
    let rows = union_test_rows(program);
    let tristate = tristate_test_target(program);

    let mut out = String::from(
        "// Code generated by box-gantry. DO NOT EDIT.\n\
         package com.box.sdk;\n\n\
         /**\n\
         \x20* Generated behavioral tests (FR-7.8, VR-4): a per-union round-trip\n\
         \x20* (known-tag dispatch, discriminator survival, open-union unknown\n\
         \x20* retention / closed-union rejection) plus the tri-state (D-110) and\n\
         \x20* date/time serialization checks, against the real generated codec.\n\
         \x20* Runs as a plain {@code main} (no test framework) — exits non-zero on\n\
         \x20* the first failure.\n\
         \x20*/\n\
         public final class GeneratedTests {\n\
         \x20   private static int _checks = 0;\n\n\
         \x20   private GeneratedTests() {}\n\n\
         \x20   public static void main(String[] args) {\n\
         \x20       serialization();\n\
         \x20       unions();\n\
         \x20       System.out.println(\"OK: \" + _checks + \" checks passed\");\n\
         \x20   }\n\n\
         \x20   private static void check(boolean cond, String message) {\n\
         \x20       _checks++;\n\
         \x20       if (!cond) {\n\
         \x20           throw new AssertionError(message);\n\
         \x20       }\n\
         \x20   }\n\n\
         \x20   private static Object parse(String json) {\n\
         \x20       return com.box.sdk.core.Json.parse(json);\n\
         \x20   }\n\n",
    );

    serialization_method(&mut out, tristate.as_ref());
    out.push('\n');
    unions_method(&mut out, &rows);

    out.push_str("}\n");
    vec![GeneratedFile {
        path: TEST_PATH.to_string(),
        content: out,
    }]
}

/// The fixed serialization checks: date/time round-trips, and — when the spec
/// has a suitable struct — the model codec's tri-state (absent / null / value).
fn serialization_method(out: &mut String, tristate: Option<&crate::models::TristateTarget>) {
    out.push_str("    private static void serialization() {\n");
    // Date / date-time round-trip through the JSON tree (the codec's string form).
    out.push_str(
        "        check(java.time.LocalDate.parse(com.box.sdk.core.Json.asString(parse(\"\\\"2026-07-12\\\"\"))).toString().equals(\"2026-07-12\"), \"date round-trip\");\n\
         \x20       java.time.OffsetDateTime _dt = java.time.OffsetDateTime.parse(\"2026-07-12T10:30:00Z\");\n\
         \x20       check(_dt.isEqual(java.time.OffsetDateTime.parse(_dt.toString())), \"date-time round-trip\");\n",
    );
    if let Some(t) = tristate {
        let s = &t.struct_fqn;
        let a = &t.accessor;
        let key = java_string_literal(&t.wire_name);
        let _ = writeln!(
            out,
            "        // tri-state (D-110) against a real struct: absent omits the key,\n\
             \x20       // null reads back null, a value round-trips.\n\
             \x20       {s} _absent = {s}.fromJson(parse(\"{{}}\"));\n\
             \x20       check(_absent.{a}().isAbsent(), \"tri-state absent: {s}\");\n\
             \x20       check(!com.box.sdk.core.Json.asObject(_absent.toJson()).containsKey({key}), \"tri-state absent omits key: {s}\");\n\
             \x20       {s} _nullv = {s}.fromJson(parse({null_json}));\n\
             \x20       check(_nullv.{a}().isNull(), \"tri-state null: {s}\");\n\
             \x20       {s} _value = {s}.fromJson(parse({value_json}));\n\
             \x20       check(_value.{a}().isPresent() && \"x\".equals(_value.{a}().value()), \"tri-state value: {s}\");",
            null_json = java_json_null(&t.wire_name),
            value_json = java_json_object(&t.wire_name, "x"),
        );
    }
    out.push_str("    }\n");
}

/// One `{ … }` block per typed union: the known-tag round-trip (when a variant's
/// minimal JSON deserializes) and the open/closed unknown-tag behavior.
fn unions_method(out: &mut String, rows: &[UnionTestRow]) {
    out.push_str("    private static void unions() {\n");
    for row in rows {
        let u = &row.union_fqn;
        let disc = &row.discriminator;
        out.push_str("        {\n");
        if let Some((tag, variant)) = &row.known {
            let known_json = java_json_object(disc, tag);
            let key = java_string_literal(disc);
            let tag_lit = java_string_literal(tag);
            let _ = writeln!(
                out,
                "            {u} _u = {u}.fromJson(parse({known_json}));\n\
                 \x20           check(_u instanceof {variant}, \"known-tag dispatch: {u}\");\n\
                 \x20           check({tag_lit}.equals(com.box.sdk.core.Json.asString(com.box.sdk.core.Json.asObject(_u.toJson()).get({key}))), \"discriminator survives: {u}\");"
            );
        }
        let unknown_json = java_json_object(disc, UNKNOWN_TAG);
        if row.open {
            let _ = writeln!(
                out,
                "            {u} _unk = {u}.fromJson(parse({unknown_json}));\n\
                 \x20           check(_unk instanceof {u}.Unknown, \"open unknown retained: {u}\");"
            );
        } else {
            let _ = writeln!(
                out,
                "            boolean _threw = false;\n\
                 \x20           try {{\n\
                 \x20               {u}.fromJson(parse({unknown_json}));\n\
                 \x20           }} catch (IllegalArgumentException _e) {{\n\
                 \x20               _threw = true;\n\
                 \x20           }}\n\
                 \x20           check(_threw, \"closed union rejects unknown: {u}\");"
            );
        }
        out.push_str("        }\n");
    }
    out.push_str("    }\n");
}

/// A Java string literal whose value is the JSON object `{"key":"value"}` — JSON
/// escaping then Java escaping, so both layers are always correct.
fn java_json_object(key: &str, value: &str) -> String {
    let json = format!("{{{}:{}}}", json_string(key), json_string(value));
    java_string_literal(&json)
}

/// A Java string literal for the JSON object `{"key":null}` (explicit null).
fn java_json_null(key: &str) -> String {
    let json = format!("{{{}:null}}", json_string(key));
    java_string_literal(&json)
}

/// A JSON-quoted string (escaping `"` and `\`).
fn json_string(s: &str) -> String {
    let mut out = String::from("\"");
    escape_into(&mut out, s);
    out.push('"');
    out
}

/// A Java string literal for raw text `s` (escaping `"` and `\`).
fn java_string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    escape_into(&mut out, s);
    out.push('"');
    out
}

/// Escape `"` and `\` — the two characters that matter for both JSON and Java
/// string bodies (discriminator wire names / tag values are otherwise plain).
fn escape_into(out: &mut String, s: &str) {
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            _ => out.push(c),
        }
    }
}
