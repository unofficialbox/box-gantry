/// A short package README (NF-8): install coordinates, a first call, and a
/// pointer at the generated `docs/` tree.
fn readme() -> String {
    format!(
        "<!-- Generated by box-gantry. DO NOT EDIT. -->\n\
         # {ARTIFACT_ID} (Java)\n\
         \n\
         A **community, unofficial** Box API client for Java — one resource\n\
         manager per API area behind a single `dev.unofficialbox.Client`, over a\n\
         dependency-free `java.net.http` runtime with retry, backoff, and token\n\
         refresh.\n\
         \n\
         > **Not affiliated with, authorized, or endorsed by Box, Inc.** \"Box\"\n\
         > is a trademark of Box, Inc. This is an independent, generated client.\n\
         \n\
         ## Install (Maven)\n\
         \n\
         ```xml\n\
         <dependency>\n\
         \x20 <groupId>{GROUP_ID}</groupId>\n\
         \x20 <artifactId>{ARTIFACT_ID}</artifactId>\n\
         \x20 <version>{VERSION}</version>\n\
         </dependency>\n\
         ```\n\
         \n\
         ## Usage\n\
         \n\
         ```java\n\
         dev.unofficialbox.Client client = new dev.unofficialbox.Client(\n\
         \x20       dev.unofficialbox.runtime.Runtime.developerToken(\"DEVELOPER_TOKEN\"));\n\
         ```\n\
         \n\
         ## Parallel chunked upload (opt-in)\n\
         \n\
         The core SDK compiles and runs on a plain JDK 26. `BoxChunkedUpload`\n\
         uploads a large file's parts **in parallel** using structured\n\
         concurrency, a Java 26 **preview** API — so it is a preview-marked class,\n\
         and code that calls it must pass `--enable-preview` at **both** compile\n\
         and run time (with `--release 26` for `javac`) to unlock the parallel path:\n\
         \n\
         ```java\n\
         // compile: javac --release 26 --enable-preview ...\n\
         // run:     java --enable-preview ...\n\
         var file = new dev.unofficialbox.BoxChunkedUpload(client)\n\
         \x20       .upload(bytes, \"large.bin\", folderId);\n\
         ```\n\
         \n\
         Everything else compiles and runs without the flag.\n\
         \n\
         See the `docs/` directory for per-manager reference and the\n\
         authentication, pagination, and errors guides.\n"
    )
}
