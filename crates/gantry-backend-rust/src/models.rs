//! Model generation: IR declarations → Rust source files.
//!
//! One Rust module per IR module. API versions redefine names (e.g.
//! `ClientError` exists in the base document and in `2025.0`), and the base
//! and versioned modules share no references, so each becomes its own module
//! rather than one flat namespace (D-147).

use std::fmt::Write as _;

use gantry_ir as ir;
use gantry_ir::naming::{constant, pascal, snake};
use gantry_sema::Analysis;

use crate::{BuildInfo, GeneratedFile};

/// Generate `src/models/mod.rs` and one `src/models/<module>.rs` per IR
/// module.
pub fn generate_models(analysis: &Analysis<'_>, build: &BuildInfo) -> Vec<GeneratedFile> {
    let program = analysis.program;

    // Group declaration indices by module, preserving program order within a
    // module so output is stable (FR-6.2).
    let mut modules: Vec<(ir::ModulePath, Vec<usize>)> = Vec::new();
    for (index, decl) in program.decls.iter().enumerate() {
        match modules.iter_mut().find(|(path, _)| *path == decl.module) {
            Some((_, indices)) => indices.push(index),
            None => modules.push((decl.module.clone(), vec![index])),
        }
    }

    let mut named: Vec<(String, &ir::ModulePath, &[usize])> = modules
        .iter()
        .map(|(path, indices)| (module_name(path), path, indices.as_slice()))
        .collect();
    named.sort_by(|a, b| a.0.cmp(&b.0));

    let mut files = vec![GeneratedFile {
        path: "src/models/mod.rs".to_string(),
        content: models_mod_rs(&named, build),
    }];
    for (name, path, indices) in &named {
        files.push(render_module(program, name, path, indices, build));
    }
    files
}

/// A Rust module name for an IR module path: every segment sanitized and
/// joined with `_`, so nested paths stay collision-free as flat siblings
/// (`[schemas, v2025_0]` → `schemas_v2025_0`).
fn module_name(module: &ir::ModulePath) -> String {
    if module.0.is_empty() {
        return "root".to_string();
    }
    module
        .0
        .iter()
        .map(|segment| sanitize_lower(segment.as_str()))
        .collect::<Vec<_>>()
        .join("_")
}

fn sanitize_lower(text: &str) -> String {
    let mut out: String = text
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    out.make_ascii_lowercase();
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, 'm');
    }
    out
}

fn models_mod_rs(named: &[(String, &ir::ModulePath, &[usize])], build: &BuildInfo) -> String {
    let mut content = format!(
        "// Code generated by box-gantry {} (spec {}). DO NOT EDIT.\n\n",
        build.engine, build.spec_fingerprint
    );
    for (name, _, _) in named {
        let _ = writeln!(content, "pub mod {name};");
    }
    content
}

fn render_module(
    program: &ir::Program,
    name: &str,
    _path: &ir::ModulePath,
    indices: &[usize],
    build: &BuildInfo,
) -> GeneratedFile {
    let api_version = indices
        .first()
        .and_then(|&i| program.decls[i].api_version.as_ref())
        .map_or("unversioned", |v| v.0.as_str());

    let mut printer = Printer {
        program,
        body: String::new(),
        uses_double_option: false,
    };
    for &index in indices {
        printer.decl(&program.decls[index]);
    }

    let mut content = format!(
        "// Code generated by box-gantry {} (spec {}) for Box API {api_version}. DO NOT EDIT.\n\n",
        build.engine, build.spec_fingerprint
    );
    if printer.uses_double_option {
        content.push_str("use crate::serde_helpers::double_option;\n\n");
    }
    content.push_str(printer.body.trim_end());
    content.push('\n');

    GeneratedFile {
        path: format!("src/models/{name}.rs"),
        content,
    }
}

struct Printer<'p> {
    program: &'p ir::Program,
    body: String,
    /// Whether any field used the tri-state deserializer, so the module gets
    /// the `use crate::serde_helpers::double_option;` import.
    uses_double_option: bool,
}

impl Printer<'_> {
    fn decl(&mut self, decl: &ir::Decl) {
        let name = type_name(decl.name.as_str());
        match &decl.kind {
            ir::DeclKind::Struct(s) => self.struct_decl(&name, s),
            ir::DeclKind::Enum(e) => self.enum_decl(&name, e),
            ir::DeclKind::Union(u) => self.union_decl(&name, u),
            ir::DeclKind::Alias(ty) => {
                let target = self.bare_type(ty);
                let _ = writeln!(self.body, "pub type {name} = {target};\n");
            }
        }
    }

    fn struct_decl(&mut self, name: &str, s: &ir::StructDecl) {
        self.body
            .push_str("#[derive(Clone, Debug, PartialEq, serde::Deserialize, serde::Serialize)]\n");
        if s.fields.is_empty() {
            let _ = writeln!(self.body, "pub struct {name} {{}}\n");
            return;
        }
        let _ = writeln!(self.body, "pub struct {name} {{");
        for field in &s.fields {
            let (ident, serde_name) = field_ident(field.name.as_str());
            let form = self.field_form(&field.ty);
            if matches!(form, FieldForm::TriState(_)) {
                self.uses_double_option = true;
            }
            emit_serde_attr(
                &mut self.body,
                &form.serde_parts(&serde_name, &field.wire_name),
            );
            emit_field(&mut self.body, &ident, &form.rust_type());
        }
        self.body.push_str("}\n\n");
    }

    /// Open enums (Box's extensible enums, D-012) lower to a newtype over
    /// `String` with the known values as associated constants — any unknown
    /// value round-trips untouched (TR-Rust.1's retention, string case).
    /// Closed enums lower to a real `enum` that rejects unknown values.
    fn enum_decl(&mut self, name: &str, e: &ir::EnumDecl) {
        match e.extensibility {
            ir::Extensibility::Open => {
                self.body.push_str(
                    "#[derive(Clone, Debug, Eq, PartialEq, serde::Deserialize, serde::Serialize)]\n",
                );
                self.body.push_str("#[serde(transparent)]\n");
                let _ = writeln!(self.body, "pub struct {name}(pub String);\n");
                if e.values.is_empty() {
                    return;
                }
                let _ = writeln!(self.body, "impl {name} {{");
                // Values that differ only in case (`ASC` vs `asc`) collapse to
                // the same SCREAMING_SNAKE_CASE constant; disambiguate the
                // duplicates so both wire values keep a named constant.
                let mut used: Vec<String> = Vec::new();
                for value in &e.values {
                    let base = constant_ident(value);
                    let mut const_name = base.clone();
                    let mut suffix = 2;
                    while used.contains(&const_name) {
                        const_name = format!("{base}_{suffix}");
                        suffix += 1;
                    }
                    used.push(const_name.clone());
                    let line = format!("    pub const {const_name}: &'static str = {value:?};");
                    if line.len() <= 100 {
                        let _ = writeln!(self.body, "{line}");
                    } else {
                        let _ = writeln!(self.body, "    pub const {const_name}: &'static str =");
                        let _ = writeln!(self.body, "        {value:?};");
                    }
                }
                self.body.push_str("}\n\n");
            }
            ir::Extensibility::Closed => {
                self.body.push_str(
                    "#[derive(Clone, Debug, Eq, PartialEq, serde::Deserialize, serde::Serialize)]\n",
                );
                let _ = writeln!(self.body, "pub enum {name} {{");
                for value in &e.values {
                    let variant = variant_ident(value);
                    let _ = writeln!(self.body, "    #[serde(rename = {value:?})]");
                    let _ = writeln!(self.body, "    {variant},");
                }
                self.body.push_str("}\n\n");
            }
        }
    }

    /// Interim union lowering (see the crate doc): a transparent newtype over
    /// `serde_json::Value`. It compiles, round-trips every value, and retains
    /// unknown discriminators for free. The serialization slice replaces this
    /// with typed serde-tagged enums (TR-Rust.1).
    fn union_decl(&mut self, name: &str, _u: &ir::UnionDecl) {
        self.body
            .push_str("#[derive(Clone, Debug, PartialEq, serde::Deserialize, serde::Serialize)]\n");
        self.body.push_str("#[serde(transparent)]\n");
        let _ = writeln!(self.body, "pub struct {name}(pub serde_json::Value);\n");
    }

    /// A bare type expression (no field-level optionality wrapping).
    fn bare_type(&self, ty: &ir::Type) -> String {
        match ty {
            ir::Type::Bool => "bool".into(),
            ir::Type::Int64 => "i64".into(),
            ir::Type::Float64 => "f64".into(),
            ir::Type::String => "String".into(),
            // Interim: RFC 3339 strings. The serialization slice introduces
            // typed date/time (TR-Rust.2 lineage).
            ir::Type::Date | ir::Type::DateTime => "String".into(),
            ir::Type::Binary => "Vec<u8>".into(),
            ir::Type::JsonValue => "serde_json::Value".into(),
            ir::Type::List(inner) => format!("Vec<{}>", self.bare_type(inner)),
            ir::Type::Map(inner) => {
                format!(
                    "std::collections::HashMap<String, {}>",
                    self.bare_type(inner)
                )
            }
            ir::Type::Decl(id) => type_name(self.program.decl(*id).name.as_str()),
            // A `Nullable`/`Optional` nested inside a container maps to
            // `Option<T>` per element.
            ir::Type::Nullable(inner) | ir::Type::Optional(inner) => {
                format!("Option<{}>", self.bare_type(inner))
            }
        }
    }

    /// How a struct field's type maps to Rust + serde (the tri-state, D-110).
    /// Arms are enumerated, never wildcarded — a new IR type must break this
    /// lowering at compile time, not fall through silently (NF-1, FR-2.1).
    fn field_form(&self, ty: &ir::Type) -> FieldForm {
        match ty {
            ir::Type::Binary => FieldForm::Binary,
            ir::Type::Optional(inner) => match &**inner {
                ir::Type::Nullable(nullable) => FieldForm::TriState(self.bare_type(nullable)),
                ir::Type::Binary => FieldForm::Binary,
                ir::Type::Bool
                | ir::Type::Int64
                | ir::Type::Float64
                | ir::Type::String
                | ir::Type::Date
                | ir::Type::DateTime
                | ir::Type::JsonValue
                | ir::Type::List(_)
                | ir::Type::Map(_)
                | ir::Type::Decl(_)
                | ir::Type::Optional(_) => FieldForm::Optional(self.bare_type(inner)),
            },
            ir::Type::Nullable(inner) => FieldForm::Nullable(self.bare_type(inner)),
            ir::Type::Bool
            | ir::Type::Int64
            | ir::Type::Float64
            | ir::Type::String
            | ir::Type::Date
            | ir::Type::DateTime
            | ir::Type::JsonValue
            | ir::Type::List(_)
            | ir::Type::Map(_)
            | ir::Type::Decl(_) => FieldForm::Plain(self.bare_type(ty)),
        }
    }
}

/// How a struct field's type maps to Rust + serde (the tri-state, D-110).
enum FieldForm {
    /// Required scalar/collection.
    Plain(String),
    /// `Optional<T>`: absent → `None`, present → `Some`.
    Optional(String),
    /// `Optional<Nullable<T>>`: absent → `None`, `null` → `Some(None)`,
    /// value → `Some(Some(v))`.
    TriState(String),
    /// Bare `Nullable<T>`: key always present, value may be `null`.
    Nullable(String),
    /// Binary payload — never JSON, skipped like Go's `json:"-"`.
    Binary,
}

impl FieldForm {
    fn rust_type(&self) -> String {
        match self {
            FieldForm::Plain(t) => t.clone(),
            FieldForm::Optional(t) | FieldForm::Nullable(t) => format!("Option<{t}>"),
            FieldForm::TriState(t) => format!("Option<Option<{t}>>"),
            FieldForm::Binary => "Vec<u8>".to_string(),
        }
    }

    /// The `#[serde(...)]` argument list for this field, in rustfmt-stable
    /// order (empty = no attribute).
    fn serde_parts(&self, serde_name: &str, wire_name: &str) -> Vec<String> {
        if matches!(self, FieldForm::Binary) {
            return vec!["skip".to_string()];
        }
        let mut parts: Vec<String> = Vec::new();
        if serde_name != wire_name {
            parts.push(format!("rename = {wire_name:?}"));
        }
        match self {
            FieldForm::Optional(_) => {
                parts.push("default".to_string());
                parts.push("skip_serializing_if = \"Option::is_none\"".to_string());
            }
            FieldForm::TriState(_) => {
                parts.push("default".to_string());
                parts.push("skip_serializing_if = \"Option::is_none\"".to_string());
                parts.push("deserialize_with = \"double_option\"".to_string());
            }
            FieldForm::Plain(_) | FieldForm::Nullable(_) => {}
            FieldForm::Binary => unreachable!("handled above"),
        }
        parts
    }
}

/// Emit a `#[serde(...)]` attribute at 4-space indent, wrapping to one
/// argument per line exactly as rustfmt does (TR-Rust.4, clean by
/// construction). rustfmt keeps a field-level attribute inline only up to 84
/// columns — `max_width` (100) minus the 16 columns it reserves at this
/// indent — and otherwise breaks one argument per line.
const RUSTFMT_ATTR_INLINE_MAX: usize = 84;

fn emit_serde_attr(body: &mut String, parts: &[String]) {
    if parts.is_empty() {
        return;
    }
    let single = format!("    #[serde({})]", parts.join(", "));
    if single.len() <= RUSTFMT_ATTR_INLINE_MAX {
        let _ = writeln!(body, "{single}");
        return;
    }
    body.push_str("    #[serde(\n");
    for (i, part) in parts.iter().enumerate() {
        let comma = if i + 1 == parts.len() { "" } else { "," };
        let _ = writeln!(body, "        {part}{comma}");
    }
    body.push_str("    )]\n");
}

/// Emit `pub <ident>: <ty>,` at 4-space indent, wrapping the type onto the
/// next line (8-space indent) when the line would overflow 100 columns.
fn emit_field(body: &mut String, ident: &str, ty: &str) {
    let line = format!("    pub {ident}: {ty},");
    if line.len() <= 100 {
        let _ = writeln!(body, "{line}");
    } else {
        let _ = writeln!(body, "    pub {ident}:");
        let _ = writeln!(body, "        {ty},");
    }
}

/// A Rust type name from an IR declaration name: PascalCase, guarded against
/// prelude/keyword collisions that would shadow.
fn type_name(name: &str) -> String {
    let pascal = pascal(name);
    if RESERVED_TYPES.contains(&pascal.as_str()) {
        format!("{pascal}_")
    } else {
        pascal
    }
}

/// A struct field identifier + the name serde uses for it by default (the
/// identifier minus any raw `r#` prefix). Rust keywords become raw
/// identifiers; the few that cannot (`self`, `crate`, `super`, `Self`) get a
/// trailing underscore.
fn field_ident(name: &str) -> (String, String) {
    let sanitized = sanitize_ident(&snake(name));
    if RAW_UNSAFE.contains(&sanitized.as_str()) {
        (format!("{sanitized}_"), format!("{sanitized}_"))
    } else if RUST_KEYWORDS.contains(&sanitized.as_str()) {
        (format!("r#{sanitized}"), sanitized.clone())
    } else {
        (sanitized.clone(), sanitized)
    }
}

/// Sanitize an arbitrary name into a valid Rust identifier body (no keyword
/// handling): non-alphanumerics → `_`, digit-leading → prefixed.
fn sanitize_ident(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    if out.is_empty() {
        out.push('_');
    }
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, 'n');
    }
    out
}

/// A closed-enum variant identifier: PascalCase, keyword- and digit-guarded.
fn variant_ident(value: &str) -> String {
    let name = constant(value);
    if RUST_KEYWORDS.contains(&name.as_str()) || RAW_UNSAFE.contains(&name.as_str()) {
        format!("{name}_")
    } else {
        name
    }
}

/// A `SCREAMING_SNAKE_CASE` associated-constant name for an open-enum value.
fn constant_ident(value: &str) -> String {
    let mut out: String = value
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    out.make_ascii_uppercase();
    // Collapse runs of underscores and trim edges for a tidy constant.
    let mut collapsed = String::with_capacity(out.len());
    let mut prev_underscore = false;
    for c in out.chars() {
        if c == '_' {
            if !prev_underscore && !collapsed.is_empty() {
                collapsed.push('_');
            }
            prev_underscore = true;
        } else {
            collapsed.push(c);
            prev_underscore = false;
        }
    }
    let trimmed = collapsed.trim_end_matches('_');
    let base = if trimmed.is_empty() { "EMPTY" } else { trimmed };
    if base.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("V{base}")
    } else {
        base.to_string()
    }
}

/// Prelude types and derive traits a generated type name must not shadow.
const RESERVED_TYPES: &[&str] = &[
    "String",
    "Vec",
    "Option",
    "Result",
    "Box",
    "Self",
    "Some",
    "None",
    "Ok",
    "Err",
    "Default",
    "Clone",
    "Debug",
    "PartialEq",
    "Eq",
    "Hash",
    "Ord",
    "Send",
    "Sync",
    "Sized",
    "Copy",
];

/// Rust keywords that are valid as raw identifiers (`r#name`).
const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield", "try", "gen",
];

/// Keywords that cannot be raw identifiers, so they get a trailing underscore.
const RAW_UNSAFE: &[&str] = &["self", "crate", "super", "Self"];

#[cfg(test)]
mod tests {
    use super::*;
    use gantry_ir::{
        Decl, DeclKind, EnumDecl, Extensibility, Field, Identifier, ModulePath, StructDecl, Type,
    };

    fn ident(s: &str) -> Identifier {
        Identifier::new(s).unwrap()
    }

    fn module() -> ModulePath {
        ModulePath(vec![ident("schemas")])
    }

    fn render(program: &ir::Program, indices: &[usize]) -> String {
        let build = BuildInfo::new("testfp");
        render_module(program, "schemas", &module(), indices, &build).content
    }

    fn add(program: &mut ir::Program, kind: DeclKind, name: &str) -> usize {
        let id = program.add(Decl {
            name: ident(name),
            module: module(),
            api_version: None,
            kind,
        });
        id.0 as usize
    }

    #[test]
    fn struct_lowers_tri_state_snake_and_keyword_fields() {
        let mut p = ir::Program::default();
        let s = add(
            &mut p,
            DeclKind::Struct(StructDecl {
                fields: vec![
                    Field {
                        name: ident("id"),
                        wire_name: "id".into(),
                        ty: Type::String,
                    },
                    Field {
                        name: ident("displayName"),
                        wire_name: "displayName".into(),
                        ty: Type::Optional(Box::new(Type::String)),
                    },
                    Field {
                        name: ident("size"),
                        wire_name: "size".into(),
                        ty: Type::Optional(Box::new(Type::Nullable(Box::new(Type::Int64)))),
                    },
                    Field {
                        name: ident("type"),
                        wire_name: "type".into(),
                        ty: Type::String,
                    },
                ],
            }),
            "Widget",
        );
        let out = render(&p, &[s]);
        assert!(out.contains("pub struct Widget {"), "{out}");
        assert!(out.contains("pub id: String,"));
        // camelCase field → snake_case ident with a serde rename to the wire.
        assert!(out.contains("pub display_name: Option<String>,"));
        assert!(out.contains(r#"rename = "displayName""#));
        // Optional<Nullable<T>> → the tri-state (D-110).
        assert!(out.contains("pub size: Option<Option<i64>>,"));
        assert!(out.contains(r#"deserialize_with = "double_option""#));
        assert!(out.contains("use crate::serde_helpers::double_option;"));
        // Keyword field → raw identifier; serde default name already matches
        // the wire, so no rename.
        assert!(out.contains("pub r#type: String,"));
    }

    #[test]
    fn open_enum_is_newtype_with_deduped_constants() {
        let mut p = ir::Program::default();
        let e = add(
            &mut p,
            DeclKind::Enum(EnumDecl {
                values: vec!["ASC".into(), "asc".into()],
                extensibility: Extensibility::Open,
            }),
            "Direction",
        );
        let out = render(&p, &[e]);
        assert!(out.contains("pub struct Direction(pub String);"), "{out}");
        // Case-only duplicates keep distinct constant names.
        assert!(out.contains(r#"pub const ASC: &'static str = "ASC";"#));
        assert!(out.contains(r#"pub const ASC_2: &'static str = "asc";"#));
    }

    #[test]
    fn closed_enum_is_a_real_enum() {
        let mut p = ir::Program::default();
        let e = add(
            &mut p,
            DeclKind::Enum(EnumDecl {
                values: vec!["on".into(), "off".into()],
                extensibility: Extensibility::Closed,
            }),
            "Mode",
        );
        let out = render(&p, &[e]);
        assert!(out.contains("pub enum Mode {"), "{out}");
        assert!(out.contains(r#"#[serde(rename = "on")]"#));
    }

    #[test]
    fn type_name_guards_prelude_collisions() {
        assert_eq!(type_name("string"), "String_");
        assert_eq!(type_name("file"), "File");
    }
}
