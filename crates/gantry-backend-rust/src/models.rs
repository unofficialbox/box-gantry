//! Model generation: IR declarations → Rust source files.
//!
//! One Rust module per IR module. API versions redefine names (e.g.
//! `ClientError` exists in the base document and in `2025.0`), and the base
//! and versioned modules share no references, so each becomes its own module
//! rather than one flat namespace (D-147).

use std::fmt::Write as _;

use gantry_ir as ir;
use gantry_ir::naming::{constant, pascal, snake};
use gantry_sema::Analysis;

use crate::{BuildInfo, GeneratedFile};

/// The one deduped, collision-free Rust module name per IR module path — the
/// single source of truth shared by the model and manager generators (D-149
/// review). Flattening a module path with `_` is not injective (`[a_b]` and
/// `[a, b]` collapse), so names are allocated deterministically here and both
/// generators consult this map rather than recomputing (which could disagree
/// on a collision).
pub(crate) fn module_names(
    program: &ir::Program,
) -> std::collections::BTreeMap<ir::ModulePath, String> {
    // Unique module paths in first-appearance order, then sorted by raw name so
    // dedup suffixes are assigned deterministically (FR-6.2).
    let mut paths: Vec<ir::ModulePath> = Vec::new();
    for decl in &program.decls {
        if !paths.contains(&decl.module) {
            paths.push(decl.module.clone());
        }
    }
    let mut named: Vec<(ir::ModulePath, String)> = paths
        .into_iter()
        .map(|p| (p.clone(), module_name(&p)))
        .collect();
    named.sort_by(|a, b| a.1.cmp(&b.1));
    let mut used: Vec<String> = Vec::new();
    let mut map = std::collections::BTreeMap::new();
    for (path, name) in named {
        map.insert(path, dedupe(&mut used, name));
    }
    map
}

/// Generate `src/models/mod.rs` and one `src/models/<module>.rs` per IR
/// module.
pub fn generate_models(analysis: &Analysis<'_>, build: &BuildInfo) -> Vec<GeneratedFile> {
    let program = analysis.program;
    let names = module_names(program);

    // Group declaration indices by module, preserving program order within a
    // module so output is stable (FR-6.2).
    let mut modules: Vec<(ir::ModulePath, Vec<usize>)> = Vec::new();
    for (index, decl) in program.decls.iter().enumerate() {
        match modules.iter_mut().find(|(path, _)| *path == decl.module) {
            Some((_, indices)) => indices.push(index),
            None => modules.push((decl.module.clone(), vec![index])),
        }
    }

    let mut named: Vec<(String, &ir::ModulePath, &[usize])> = modules
        .iter()
        .map(|(path, indices)| (names[path].clone(), path, indices.as_slice()))
        .collect();
    named.sort_by(|a, b| a.0.cmp(&b.0));

    let mut files = vec![GeneratedFile {
        path: "src/models/mod.rs".to_string(),
        content: models_mod_rs(&named, build),
    }];
    for (name, path, indices) in &named {
        files.push(render_module(program, name, path, indices, build));
    }
    files
}

/// A Rust module name for an IR module path: every segment sanitized and
/// joined with `_`, so nested paths stay collision-free as flat siblings
/// (`[schemas, v2025_0]` → `schemas_v2025_0`).
pub(crate) fn module_name(module: &ir::ModulePath) -> String {
    if module.0.is_empty() {
        return "root".to_string();
    }
    let joined = module
        .0
        .iter()
        .map(|segment| sanitize_lower(segment.as_str()))
        .collect::<Vec<_>>()
        .join("_");
    // A single-segment path that lands on a keyword (`type`) would emit an
    // invalid `pub mod type;` — suffix it.
    if RUST_KEYWORDS.contains(&joined.as_str()) || RAW_UNSAFE.contains(&joined.as_str()) {
        format!("{joined}_")
    } else {
        joined
    }
}

fn sanitize_lower(text: &str) -> String {
    let mut out: String = text
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    out.make_ascii_lowercase();
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, 'm');
    }
    out
}

fn models_mod_rs(named: &[(String, &ir::ModulePath, &[usize])], build: &BuildInfo) -> String {
    let mut content = format!(
        "// Code generated by box-gantry {} (spec {}). DO NOT EDIT.\n\n",
        build.engine, build.spec_fingerprint
    );
    for (name, _, _) in named {
        let _ = writeln!(content, "pub mod {name};");
    }
    content
}

fn render_module(
    program: &ir::Program,
    name: &str,
    _path: &ir::ModulePath,
    indices: &[usize],
    build: &BuildInfo,
) -> GeneratedFile {
    let api_version = indices
        .first()
        .and_then(|&i| program.decls[i].api_version.as_ref())
        .map_or("unversioned", |v| v.0.as_str());

    let mut printer = Printer {
        program,
        body: String::new(),
        uses_double_option: false,
    };
    for &index in indices {
        printer.decl(&program.decls[index]);
    }

    let mut content = format!(
        "// Code generated by box-gantry {} (spec {}) for Box API {api_version}. DO NOT EDIT.\n\n",
        build.engine, build.spec_fingerprint
    );
    if printer.uses_double_option {
        content.push_str("use crate::serde_helpers::double_option;\n\n");
    }
    content.push_str(printer.body.trim_end());
    content.push('\n');

    GeneratedFile {
        path: format!("src/models/{name}.rs"),
        content,
    }
}

struct Printer<'p> {
    program: &'p ir::Program,
    body: String,
    /// Whether any field used the tri-state deserializer, so the module gets
    /// the `use crate::serde_helpers::double_option;` import.
    uses_double_option: bool,
}

impl Printer<'_> {
    fn decl(&mut self, decl: &ir::Decl) {
        let name = type_name(decl.name.as_str());
        match &decl.kind {
            ir::DeclKind::Struct(s) => self.struct_decl(&name, s),
            ir::DeclKind::Enum(e) => self.enum_decl(&name, e),
            ir::DeclKind::Union(u) => self.union_decl(&name, u),
            ir::DeclKind::Alias(ty) => {
                let target = self.bare_type(ty);
                let _ = writeln!(self.body, "pub type {name} = {target};\n");
            }
        }
    }

    fn struct_decl(&mut self, name: &str, s: &ir::StructDecl) {
        self.body
            .push_str("#[derive(Clone, Debug, PartialEq, serde::Deserialize, serde::Serialize)]\n");
        if s.fields.is_empty() {
            let _ = writeln!(self.body, "pub struct {name} {{}}\n");
            return;
        }
        let _ = writeln!(self.body, "pub struct {name} {{");
        // Distinct source names can normalize to the same Rust identifier
        // (`displayName` and `display_name` both → `display_name`); a per-struct
        // allocator keeps them distinct so the crate compiles.
        let mut used: Vec<String> = Vec::new();
        for field in &s.fields {
            let base = dedupe(&mut used, field_base(field.name.as_str()));
            let (ident, serde_name) = keyword_wrap(&base);
            let form = self.field_form(&field.ty);
            if matches!(form, FieldForm::TriState(_)) {
                self.uses_double_option = true;
            }
            emit_serde_attr(
                &mut self.body,
                &form.serde_parts(&serde_name, &field.wire_name),
            );
            emit_field(&mut self.body, &ident, &form.rust_type());
        }
        self.body.push_str("}\n\n");
    }

    /// Open enums (Box's extensible enums, D-012) lower to a newtype over
    /// `String` with the known values as associated constants — any unknown
    /// value round-trips untouched (TR-Rust.1's retention, string case).
    /// Closed enums lower to a real `enum` that rejects unknown values.
    fn enum_decl(&mut self, name: &str, e: &ir::EnumDecl) {
        match e.extensibility {
            ir::Extensibility::Open => {
                self.body.push_str(
                    "#[derive(Clone, Debug, Eq, PartialEq, serde::Deserialize, serde::Serialize)]\n",
                );
                self.body.push_str("#[serde(transparent)]\n");
                let _ = writeln!(self.body, "pub struct {name}(pub String);\n");
                if e.values.is_empty() {
                    return;
                }
                let _ = writeln!(self.body, "impl {name} {{");
                // Values that differ only in case (`ASC` vs `asc`) collapse to
                // the same SCREAMING_SNAKE_CASE constant; disambiguate the
                // duplicates so both wire values keep a named constant.
                let mut used: Vec<String> = Vec::new();
                for value in &e.values {
                    let const_name = dedupe(&mut used, constant_ident(value));
                    let line = format!("    pub const {const_name}: &'static str = {value:?};");
                    if line.len() <= 100 {
                        let _ = writeln!(self.body, "{line}");
                    } else {
                        let _ = writeln!(self.body, "    pub const {const_name}: &'static str =");
                        let _ = writeln!(self.body, "        {value:?};");
                    }
                }
                self.body.push_str("}\n\n");
            }
            ir::Extensibility::Closed => {
                self.body.push_str(
                    "#[derive(Clone, Debug, Eq, PartialEq, serde::Deserialize, serde::Serialize)]\n",
                );
                let _ = writeln!(self.body, "pub enum {name} {{");
                // Distinct values can normalize to the same variant identifier
                // (`foo-bar` and `foo_bar`); keep them apart. The serde rename
                // always names the exact wire value, so dispatch stays correct.
                let mut used: Vec<String> = Vec::new();
                for value in &e.values {
                    let variant = dedupe(&mut used, variant_ident(value));
                    let _ = writeln!(self.body, "    #[serde(rename = {value:?})]");
                    let _ = writeln!(self.body, "    {variant},");
                }
                self.body.push_str("}\n\n");
            }
        }
    }

    /// Union lowering (TR-Rust.1). A union that carries a discriminator and
    /// whose every variant pairs a discriminator value with a decl-backed type
    /// lowers to a typed `enum` with hand-written `Serialize`/`Deserialize`
    /// that dispatch on the tag (mirroring the Go backend, D-147 lineage):
    /// serialize delegates to the active variant — whose own field carries the
    /// discriminator, so no tag is injected or duplicated — and deserialize
    /// peeks at the tag and routes to the variant. Open unions retain an
    /// unrecognized tag in an `Unknown(serde_json::Value)` variant (round-trip
    /// safe, VR-4); closed unions reject it.
    ///
    /// The typed form is only sound when every variant's struct actually
    /// carries the discriminator field — that field *is* the serialized tag, so
    /// a variant missing it would drop the discriminator on round-trip. Any
    /// union that doesn't meet the bar (no discriminator, a non-decl variant,
    /// or a variant whose decl lacks the discriminator field) is structural and
    /// lowers to a transparent `serde_json::Value` newtype — callers inspect
    /// the raw value.
    fn union_decl(&mut self, name: &str, u: &ir::UnionDecl) {
        let discriminated: Option<Vec<(&str, ir::DeclId)>> = match &u.discriminator {
            Some(discriminator) => u
                .variants
                .iter()
                .map(|v| match (&v.discriminator_value, &v.ty) {
                    (Some(value), ir::Type::Decl(id))
                        if self.decl_carries_field(*id, discriminator) =>
                    {
                        Some((value.as_str(), *id))
                    }
                    _ => None,
                })
                .collect(),
            None => None,
        };
        match (discriminated, &u.discriminator) {
            (Some(variants), Some(discriminator)) => {
                self.discriminated_union(name, discriminator, &variants, u.extensibility);
            }
            _ => self.structural_union(name),
        }
    }

    /// Whether a declaration is a struct with a field serialized under
    /// `wire_name` — i.e. it carries its own discriminator, the invariant the
    /// typed-union serialization relies on.
    fn decl_carries_field(&self, id: ir::DeclId, wire_name: &str) -> bool {
        matches!(
            &self.program.decl(id).kind,
            ir::DeclKind::Struct(s) if s.fields.iter().any(|f| f.wire_name == wire_name)
        )
    }

    /// The structural fallback: a transparent newtype over `serde_json::Value`.
    fn structural_union(&mut self, name: &str) {
        self.body
            .push_str("#[derive(Clone, Debug, PartialEq, serde::Deserialize, serde::Serialize)]\n");
        self.body.push_str("#[serde(transparent)]\n");
        let _ = writeln!(self.body, "pub struct {name}(pub serde_json::Value);\n");
    }

    fn discriminated_union(
        &mut self,
        name: &str,
        discriminator: &str,
        variants: &[(&str, ir::DeclId)],
        extensibility: ir::Extensibility,
    ) {
        let open = matches!(extensibility, ir::Extensibility::Open);
        // Variant identifier from the discriminator value (`ai_agent_ask` →
        // `AiAgentAsk`), de-duplicated and kept clear of the `Unknown` arm.
        let mut used: Vec<String> = if open {
            vec!["Unknown".to_string()]
        } else {
            Vec::new()
        };
        let rows: Vec<(String, String, &str)> = variants
            .iter()
            .map(|(value, id)| {
                let variant = dedupe(&mut used, variant_ident(value));
                let ty = type_name(self.program.decl(*id).name.as_str());
                (variant, ty, *value)
            })
            .collect();

        // The enum. serde derives are hand-written below, so only the value
        // traits are derived here.
        self.body.push_str("#[derive(Clone, Debug, PartialEq)]\n");
        let _ = writeln!(self.body, "pub enum {name} {{");
        for (variant, ty, _) in &rows {
            let _ = writeln!(self.body, "    {variant}({ty}),");
        }
        if open {
            self.body.push_str(
                "    /// An unrecognized discriminator, retained verbatim (open union).\n",
            );
            self.body.push_str("    Unknown(serde_json::Value),\n");
        }
        self.body.push_str("}\n\n");

        // Serialize: delegate to the active variant; its own discriminator
        // field is the tag, so nothing is injected.
        let _ = writeln!(self.body, "impl serde::Serialize for {name} {{");
        self.body.push_str(
            "    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {\n",
        );
        self.body.push_str("        match self {\n");
        for (variant, _, _) in &rows {
            let _ = writeln!(
                self.body,
                "            Self::{variant}(inner) => inner.serialize(serializer),"
            );
        }
        if open {
            self.body
                .push_str("            Self::Unknown(inner) => inner.serialize(serializer),\n");
        }
        self.body.push_str("        }\n    }\n}\n\n");

        // Deserialize: peek at the tag, route to the variant, retain unknowns.
        let _ = writeln!(self.body, "impl<'de> serde::Deserialize<'de> for {name} {{");
        self.body.push_str(
            "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {\n",
        );
        self.body
            .push_str("        let value = serde_json::Value::deserialize(deserializer)?;\n");
        // rustfmt always breaks this method chain (it exceeds chain_width),
        // so emit the broken form directly (clean by construction).
        self.body.push_str("        let tag = value\n");
        let _ = writeln!(self.body, "            .get({discriminator:?})");
        self.body
            .push_str("            .and_then(serde_json::Value::as_str)\n");
        self.body.push_str("            .map(str::to_owned);\n");
        self.body.push_str("        match tag.as_deref() {\n");
        for (variant, _, value) in &rows {
            let _ = writeln!(
                self.body,
                "            Some({value:?}) => Ok(Self::{variant}("
            );
            self.body.push_str(
                "                serde_json::from_value(value).map_err(serde::de::Error::custom)?,\n",
            );
            self.body.push_str("            )),\n");
        }
        if open {
            self.body
                .push_str("            _ => Ok(Self::Unknown(value)),\n");
        } else {
            let _ = writeln!(
                self.body,
                "            other => Err(serde::de::Error::custom(format!(",
            );
            let _ = writeln!(
                self.body,
                "                \"unrecognized {discriminator} discriminator: {{other:?}}\""
            );
            self.body.push_str("            ))),\n");
        }
        self.body.push_str("        }\n    }\n}\n\n");
    }

    /// A bare type expression (no field-level optionality wrapping).
    fn bare_type(&self, ty: &ir::Type) -> String {
        match ty {
            ir::Type::Bool => "bool".into(),
            ir::Type::Int64 => "i64".into(),
            ir::Type::Float64 => "f64".into(),
            ir::Type::String => "String".into(),
            // Typed date/time (chrono): a full-date `NaiveDate` (Box's
            // `2020-01-31`) and an RFC 3339 `DateTime<Utc>` — both serde-serialize
            // to exactly Box's wire format, mirroring Go's `serialization.Date` +
            // `time.Time`.
            ir::Type::Date => "chrono::NaiveDate".into(),
            ir::Type::DateTime => "chrono::DateTime<chrono::Utc>".into(),
            ir::Type::Binary => "Vec<u8>".into(),
            ir::Type::JsonValue => "serde_json::Value".into(),
            ir::Type::List(inner) => format!("Vec<{}>", self.bare_type(inner)),
            ir::Type::Map(inner) => {
                format!(
                    "std::collections::HashMap<String, {}>",
                    self.bare_type(inner)
                )
            }
            ir::Type::Decl(id) => type_name(self.program.decl(*id).name.as_str()),
            // A `Nullable`/`Optional` nested inside a container maps to
            // `Option<T>` per element.
            ir::Type::Nullable(inner) | ir::Type::Optional(inner) => {
                format!("Option<{}>", self.bare_type(inner))
            }
        }
    }

    /// How a struct field's type maps to Rust + serde (the tri-state, D-110).
    /// Arms are enumerated, never wildcarded — a new IR type must break this
    /// lowering at compile time, not fall through silently (NF-1, FR-2.1).
    fn field_form(&self, ty: &ir::Type) -> FieldForm {
        match ty {
            ir::Type::Binary => FieldForm::Binary,
            ir::Type::Optional(inner) => match &**inner {
                ir::Type::Nullable(nullable) => FieldForm::TriState(self.bare_type(nullable)),
                ir::Type::Binary => FieldForm::Binary,
                ir::Type::Bool
                | ir::Type::Int64
                | ir::Type::Float64
                | ir::Type::String
                | ir::Type::Date
                | ir::Type::DateTime
                | ir::Type::JsonValue
                | ir::Type::List(_)
                | ir::Type::Map(_)
                | ir::Type::Decl(_)
                | ir::Type::Optional(_) => FieldForm::Optional(self.bare_type(inner)),
            },
            ir::Type::Nullable(inner) => FieldForm::Nullable(self.bare_type(inner)),
            ir::Type::Bool
            | ir::Type::Int64
            | ir::Type::Float64
            | ir::Type::String
            | ir::Type::Date
            | ir::Type::DateTime
            | ir::Type::JsonValue
            | ir::Type::List(_)
            | ir::Type::Map(_)
            | ir::Type::Decl(_) => FieldForm::Plain(self.bare_type(ty)),
        }
    }
}

/// How a struct field's type maps to Rust + serde (the tri-state, D-110).
enum FieldForm {
    /// Required scalar/collection.
    Plain(String),
    /// `Optional<T>`: absent → `None`, present → `Some`.
    Optional(String),
    /// `Optional<Nullable<T>>`: absent → `None`, `null` → `Some(None)`,
    /// value → `Some(Some(v))`.
    TriState(String),
    /// Bare `Nullable<T>`: key always present, value may be `null`.
    Nullable(String),
    /// Binary payload — never JSON, skipped like Go's `json:"-"`.
    Binary,
}

impl FieldForm {
    fn rust_type(&self) -> String {
        match self {
            FieldForm::Plain(t) => t.clone(),
            FieldForm::Optional(t) | FieldForm::Nullable(t) => format!("Option<{t}>"),
            FieldForm::TriState(t) => format!("Option<Option<{t}>>"),
            FieldForm::Binary => "Vec<u8>".to_string(),
        }
    }

    /// The `#[serde(...)]` argument list for this field, in rustfmt-stable
    /// order (empty = no attribute).
    fn serde_parts(&self, serde_name: &str, wire_name: &str) -> Vec<String> {
        if matches!(self, FieldForm::Binary) {
            return vec!["skip".to_string()];
        }
        let mut parts: Vec<String> = Vec::new();
        if serde_name != wire_name {
            parts.push(format!("rename = {wire_name:?}"));
        }
        match self {
            FieldForm::Optional(_) => {
                parts.push("default".to_string());
                parts.push("skip_serializing_if = \"Option::is_none\"".to_string());
            }
            FieldForm::TriState(_) => {
                parts.push("default".to_string());
                parts.push("skip_serializing_if = \"Option::is_none\"".to_string());
                parts.push("deserialize_with = \"double_option\"".to_string());
            }
            FieldForm::Plain(_) | FieldForm::Nullable(_) => {}
            FieldForm::Binary => unreachable!("handled above"),
        }
        parts
    }
}

/// Emit a `#[serde(...)]` attribute at 4-space indent, wrapping to one
/// argument per line exactly as rustfmt does (TR-Rust.4, clean by
/// construction). rustfmt keeps a field-level attribute inline only up to 84
/// columns — `max_width` (100) minus the 16 columns it reserves at this
/// indent — and otherwise breaks one argument per line.
const RUSTFMT_ATTR_INLINE_MAX: usize = 84;

fn emit_serde_attr(body: &mut String, parts: &[String]) {
    if parts.is_empty() {
        return;
    }
    let single = format!("    #[serde({})]", parts.join(", "));
    if single.len() <= RUSTFMT_ATTR_INLINE_MAX {
        let _ = writeln!(body, "{single}");
        return;
    }
    body.push_str("    #[serde(\n");
    for (i, part) in parts.iter().enumerate() {
        let comma = if i + 1 == parts.len() { "" } else { "," };
        let _ = writeln!(body, "        {part}{comma}");
    }
    body.push_str("    )]\n");
}

/// Emit `pub <ident>: <ty>,` at 4-space indent, wrapping the type onto the
/// next line (8-space indent) when the line would overflow 100 columns.
fn emit_field(body: &mut String, ident: &str, ty: &str) {
    let line = format!("    pub {ident}: {ty},");
    if line.len() <= 100 {
        let _ = writeln!(body, "{line}");
    } else {
        let _ = writeln!(body, "    pub {ident}:");
        let _ = writeln!(body, "        {ty},");
    }
}

/// A Rust type name from an IR declaration name: PascalCase, guarded against
/// prelude/keyword collisions that would shadow.
pub(crate) fn type_name(name: &str) -> String {
    let pascal = pascal(name);
    if RESERVED_TYPES.contains(&pascal.as_str()) {
        format!("{pascal}_")
    } else {
        pascal
    }
}

/// The normalized `snake_case` body of a field identifier, before keyword
/// wrapping and per-scope de-duplication.
fn field_base(name: &str) -> String {
    sanitize_ident(&snake(name))
}

/// Wrap an already-unique identifier base into (token, serde-default-name):
/// Rust keywords become raw identifiers; the few that cannot (`self`, `crate`,
/// `super`, `Self`) get a trailing underscore. De-duplication runs *before*
/// this, so a suffixed base like `type_2` is never a keyword here.
fn keyword_wrap(base: &str) -> (String, String) {
    if RAW_UNSAFE.contains(&base) {
        (format!("{base}_"), format!("{base}_"))
    } else if RUST_KEYWORDS.contains(&base) {
        (format!("r#{base}"), base.to_string())
    } else {
        (base.to_string(), base.to_string())
    }
}

/// Allocate a collision-free name in a scope: returns `base` if unused, else
/// `base_2`, `base_3`, … Deterministic given a stable iteration order (FR-6.2).
fn dedupe(used: &mut Vec<String>, base: String) -> String {
    let mut candidate = base.clone();
    let mut n = 2;
    while used.contains(&candidate) {
        candidate = format!("{base}_{n}");
        n += 1;
    }
    used.push(candidate.clone());
    candidate
}

/// Sanitize an arbitrary name into a valid Rust identifier body (no keyword
/// handling): non-alphanumerics → `_`, digit-leading → prefixed.
fn sanitize_ident(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    if out.is_empty() {
        out.push('_');
    }
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, 'n');
    }
    out
}

/// A closed-enum variant identifier: PascalCase, keyword- and digit-guarded.
pub(crate) fn variant_ident(value: &str) -> String {
    let name = constant(value);
    if RUST_KEYWORDS.contains(&name.as_str()) || RAW_UNSAFE.contains(&name.as_str()) {
        format!("{name}_")
    } else {
        name
    }
}

/// A `SCREAMING_SNAKE_CASE` associated-constant name for an open-enum value.
fn constant_ident(value: &str) -> String {
    let mut out: String = value
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    out.make_ascii_uppercase();
    // Collapse runs of underscores and trim edges for a tidy constant.
    let mut collapsed = String::with_capacity(out.len());
    let mut prev_underscore = false;
    for c in out.chars() {
        if c == '_' {
            if !prev_underscore && !collapsed.is_empty() {
                collapsed.push('_');
            }
            prev_underscore = true;
        } else {
            collapsed.push(c);
            prev_underscore = false;
        }
    }
    let trimmed = collapsed.trim_end_matches('_');
    let base = if trimmed.is_empty() { "EMPTY" } else { trimmed };
    if base.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("V{base}")
    } else {
        base.to_string()
    }
}

