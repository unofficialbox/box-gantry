/// A `snake_case` identifier for a parameter/field, keyword-safe.
fn field_ident(name: &str) -> String {
    let base = snake(name);
    let base = if base.is_empty() {
        "field".to_string()
    } else if base.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("n{base}")
    } else {
        base
    };
    if RUST_KEYWORDS.contains(&base.as_str()) {
        format!("r#{base}")
    } else if RAW_UNSAFE.contains(&base.as_str()) {
        format!("{base}_")
    } else {
        base
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield", "try", "gen",
];

const RAW_UNSAFE: &[&str] = &["self", "crate", "super", "Self"];

/// Generation-side helpers embedded in the SDK (not part of the runtime
/// contract): RFC 3986 path-segment percent-encoding.
const INTERNAL: &str = "\
// Code generated by box-gantry. DO NOT EDIT.

/// Comma-join a slice into a query value, converting each element with `f`.
pub(crate) fn join<T>(items: &[T], f: impl Fn(&T) -> String) -> String {
    items.iter().map(f).collect::<Vec<_>>().join(\",\")
}

/// Percent-encode a value, leaving RFC 3986 unreserved characters as-is.
pub(crate) fn path_escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for &byte in value.as_bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'.' | b'_' | b'~' => {
                out.push(byte as char);
            }
            _ => {
                out.push('%');
                out.push_str(&format!(\"{byte:02X}\"));
            }
        }
    }
    out
}

/// application/x-www-form-urlencoded body from key/value pairs (the OAuth2
/// token endpoints): each key and value percent-encoded, joined by `&`.
pub(crate) fn form_encode(pairs: &[(&str, String)]) -> String {
    let mut out = String::new();
    for (index, (key, value)) in pairs.iter().enumerate() {
        if index > 0 {
            out.push('&');
        }
        out.push_str(&path_escape(key));
        out.push('=');
        out.push_str(&path_escape(value));
    }
    out
}
";

