//! Manager + client generation: IR operations → async Rust methods that call
//! only through the runtime contract (FR-5.2, TR-Rust.3).
//!
//! One `<Name>Manager` per `x-box-tag`, one `async fn` per operation, and a
//! `Client` entry point wiring a shared runtime session. Methods build the URL
//! from structured path segments (never a re-parsed template, FR-2.2), apply
//! query/header params, encode the request body per media, `fetch` through the
//! session, and decode the response by shape. Optional params travel in a
//! per-operation options struct. Everything reaches the network only via
//! `crate::runtime` (the contract surface), so the generated SDK compiles
//! against the rendered stubs and, later, the real runtime unchanged.

use std::collections::HashMap;
use std::fmt::Write as _;

use gantry_ir as ir;
use gantry_ir::naming::{append_without_repeating, pascal, snake};
use gantry_sema::Analysis;
use gantry_synth::{
    ACCESS_TOKEN_TYPE, EventStream, PageStyle, PagedOperation, PositionShape, TOKEN_EXCHANGE_GRANT,
    TokenExchange, ZipDownload, detect_event_streams, detect_pagination, detect_token_exchanges,
    detect_zip_downloads,
};

use crate::models::type_name;
use crate::{BuildInfo, GeneratedFile};

/// Managers reference the runtime through a per-file `use crate::runtime`, so
/// generated paths stay short enough to keep signatures rustfmt-inline.
const RUNTIME: &str = "runtime";

/// The deduped, keyword-safe Rust names for one manager: its module/file, its
/// struct, and its `Client` field — all derived from one collision-free base.
pub(crate) struct ManagerName {
    pub(crate) module: String,
    struct_name: String,
    field: String,
}

/// Allocate one collision-free, keyword-safe [`ManagerName`] per manager
/// (sorted keys via the `BTreeMap`), reused for the module, file, struct, and
/// field. The single source of truth for manager naming, so `managers.rs` and
/// the per-manager schema-file split in `models.rs` (D-201) can't disagree on
/// what a manager tag's module is called.
pub(crate) fn plan_managers<'a>(
    analysis: &'a Analysis<'_>,
) -> Vec<(&'a String, &'a Vec<usize>, ManagerName)> {
    let mut used: Vec<String> = Vec::new();
    analysis
        .managers
        .iter()
        .map(|(key, indices)| {
            let base = dedupe(&mut used, safe_module_base(key));
            let name = ManagerName {
                struct_name: format!("{}Manager", pascal(&base)),
                field: base.clone(),
                module: base,
            };
            (key, indices, name)
        })
        .collect()
}

/// Generate the `managers` module (one file per manager), the `client` entry
/// point, and the `internal` helpers.
pub fn generate_managers(analysis: &Analysis<'_>, _build: &BuildInfo) -> Vec<GeneratedFile> {
    let program = analysis.program;
    let base_version = program.base_api_version().cloned();
    // Shared module-name registry, so manager type paths agree with the models
    // (D-149 review).
    let modules = crate::models::module_names(program);
    // Paginated operations, by operation index (FR-7.3): each gets an async
    // paginator alongside its plain method.
    let paged: HashMap<usize, PagedOperation> = detect_pagination(analysis)
        .into_iter()
        .map(|p| (p.operation, p))
        .collect();

    let streams = detect_event_streams(analysis);
    let representations = gantry_synth::detect_representations(analysis);
    let exchanges = detect_token_exchanges(analysis);
    let zips = detect_zip_downloads(analysis);

    let named = plan_managers(analysis);

    let mut files = Vec::new();

    let mut mod_rs = String::from("// Code generated by box-gantry. DO NOT EDIT.\n\n");
    for (_, _, name) in &named {
        let _ = writeln!(mod_rs, "pub mod {};", name.module);
    }
    files.push(GeneratedFile {
        path: "src/managers/mod.rs".to_string(),
        content: mod_rs,
    });

    for (key, indices, name) in &named {
        let mut p = Printer {
            program,
            base_version: base_version.clone(),
            modules: &modules,
            paged: &paged,
            streams: &streams,
            representations: &representations,
            exchanges: &exchanges,
            zips: &zips,
            body: String::new(),
            uses_path_escape: false,
        };
        p.manager(key, name, indices);
        let mut content = String::from("// Code generated by box-gantry. DO NOT EDIT.\n\n");
        // Alphabetical (rustfmt import order): `internal` before `runtime`.
        if p.uses_path_escape {
            content.push_str("use crate::internal::path_escape;\n");
        }
        content.push_str("use crate::runtime::{self, Error};\n");
        content.push('\n');
        content.push_str(p.body.trim_end());
        content.push('\n');
        files.push(GeneratedFile {
            path: format!("src/managers/{}.rs", name.module),
            content,
        });
    }

    files.push(GeneratedFile {
        path: "src/client.rs".to_string(),
        content: client_file(&named),
    });
    files.push(GeneratedFile {
        path: "src/internal.rs".to_string(),
        content: INTERNAL.to_string(),
    });
    files
}

/// A collision-free base for a manager: `snake`, keyword-suffixed, digit-safe.
fn safe_module_base(key: &str) -> String {
    let base = snake(key);
    let base = if base.is_empty() {
        "manager".to_string()
    } else if base.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("m{base}")
    } else {
        base
    };
    if RUST_KEYWORDS.contains(&base.as_str()) || RAW_UNSAFE.contains(&base.as_str()) {
        format!("{base}_")
    } else {
        base
    }
}

/// The `Client` entry point: one field per manager, a shared runtime session.
fn client_file(named: &[(&String, &Vec<usize>, ManagerName)]) -> String {
    let mut out = String::from("// Code generated by box-gantry. DO NOT EDIT.\n\n");
    out.push_str("/// The Box SDK client: one manager per API area over a shared session.\n");
    out.push_str("pub struct Client {\n");
    for (_, _, name) in named {
        let _ = writeln!(
            out,
            "    pub {field}: crate::managers::{module}::{ty},",
            field = name.field,
            module = name.module,
            ty = name.struct_name,
        );
    }
    // The private session field backs `with_as_user_header`; a manager field
    // of the same name would clash with it, so refuse loudly rather than rename.
    assert!(
        named.iter().all(|(_, _, name)| name.field != "session"),
        "a manager field named `session` collides with Client's runtime session"
    );
    out.push_str("    session: std::sync::Arc<crate::runtime::Client>,\n");
    out.push_str("}\n\n");
    out.push_str("impl Client {\n");
    out.push_str("    /// Build a client for an authentication flow.\n");
    out.push_str("    pub fn new(auth: crate::runtime::Auth) -> Self {\n");
    out.push_str("        Self::from_session(crate::runtime::Client::new(auth))\n");
    out.push_str("    }\n\n");
    out.push_str(
        "    /// Build a client over a configured runtime session — retries, an\n    \
         /// injected HTTP client or HTTP version, default headers, base URLs.\n",
    );
    out.push_str("    pub fn from_session(session: crate::runtime::Client) -> Self {\n");
    out.push_str("        let session = std::sync::Arc::new(session);\n");
    out.push_str("        Self {\n");
    for (_, _, name) in named {
        let _ = writeln!(
            out,
            "            {field}: crate::managers::{module}::{ty}::new(session.clone()),",
            field = name.field,
            module = name.module,
            ty = name.struct_name,
        );
    }
    out.push_str("            session,\n");
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    /// A new client whose every API call acts as the user `user_id` (Box's\n    \
         /// `As-User` header). It shares this client's auth and configuration;\n    \
         /// this client is unchanged.\n",
    );
    out.push_str("    pub fn with_as_user_header(&self, user_id: &str) -> Self {\n");
    out.push_str("        Self::from_session(self.session.with_as_user_header(user_id))\n");
    out.push_str("    }\n}\n");
    out
}

struct Printer<'p> {
    program: &'p ir::Program,
    base_version: Option<ir::ApiVersion>,
    /// Shared IR-module → Rust-module-name map (D-149 review).
    modules: &'p std::collections::BTreeMap<ir::ModulePath, String>,
    /// Paginated operations by index (FR-7.3).
    paged: &'p HashMap<usize, PagedOperation>,
    /// Event streams, so a stream's manager gains `stream`.
    streams: &'p [EventStream],
    /// Token exchanges, so an exchange's manager gains `downscope_token`.
    exchanges: &'p [TokenExchange],
    /// Zip downloads, so a zip's manager gains `download_zip`.
    zips: &'p [ZipDownload],
    /// Representation sources, so a source's manager gains
    /// `get_representation_content`.
    representations: &'p [gantry_synth::Representation],
    body: String,
    /// Whether any method escaped a path parameter, so the file imports
    /// `path_escape`.
    uses_path_escape: bool,
}

impl Printer<'_> {
    fn manager(&mut self, key: &str, name: &ManagerName, indices: &[usize]) {
        let ty = &name.struct_name;
        // One deduped method name per operation (distinct source ops can
        // normalize to the same `snake` name), reused for the method, its doc,
        // and its options struct so the surface can't collide (D-149 review).
        // A paged operation whose cursor shape actually synthesizes also
        // reserves its private `<method>_page` fetch name in the same pool,
        // right after computing its plan, so that name can't collide with a
        // later operation's either — public or private (#78). Reserving it
        // any earlier — e.g. as soon as the operation is merely a
        // `detect_pagination` hit — would be premature: that detection
        // matches wire shape only, not the cursor's scalar type, so it can
        // still miss here (`pagination_plan` returns `None`), and a name
        // nothing is ever emitted under must not consume a dedup slot.
        let mut used = Vec::new();
        let mut methods: Vec<String> = Vec::with_capacity(indices.len());
        let mut variants: Vec<Option<String>> = Vec::with_capacity(indices.len());
        let mut plans: Vec<Option<PaginationPlan>> = Vec::with_capacity(indices.len());
        for &index in indices {
            let op = &self.program.operations[index];
            let method = dedupe(&mut used, method_name(op));
            // A conditional read's `<method>_if_modified` variant is public too.
            variants.push(op.conditional.as_ref().map(|read| {
                let variant = ir::Operation {
                    name: read.name.clone(),
                    ..op.clone()
                };
                dedupe(&mut used, method_name(&variant))
            }));
            let plan = self
                .paged
                .get(&index)
                .and_then(|paged| self.pagination_plan(op, name, &method, paged))
                .map(|mut plan| {
                    plan.method = dedupe(&mut used, plan.method);
                    plan
                });
            methods.push(method);
            plans.push(plan);
        }

        // Options structs and paginators are module-level items (Rust forbids
        // `struct` inside `impl`), emitted before the manager so the methods can
        // name them.
        for (pos, &index) in indices.iter().enumerate() {
            let op = self.program.operations[index].clone();
            self.options_struct(&op, ty, &methods[pos]);
        }
        for plan in plans.iter().flatten() {
            self.paginator_type(plan);
        }
        let _ = writeln!(
            self.body,
            "/// Operations for the {key:?} API area.\n\
             pub struct {ty} {{\n\
             \x20   session: std::sync::Arc<{RUNTIME}::Client>,\n\
             }}\n\n\
             impl {ty} {{\n\
             \x20   pub(crate) fn new(session: std::sync::Arc<{RUNTIME}::Client>) -> Self {{\n\
             \x20       Self {{ session }}\n\
             \x20   }}"
        );
        for (pos, &index) in indices.iter().enumerate() {
            let op = self.program.operations[index].clone();
            match &plans[pos] {
                // Option A (FR-7.3): the public `<method>` returns the
                // auto-paging paginator; the single-page fetch it drives ships as
                // the private `<method>_page` (same module, so reachable).
                Some(plan) => {
                    self.operation(&op, &plan.method, &methods[pos], false);
                    self.paginate_method(&op, &methods[pos], plan);
                }
                // No paginator synthesized: the plain single-page `<method>`
                // ships as the public entry point (VR-6).
                None => {
                    self.operation(&op, &methods[pos], &methods[pos], true);
                    if let (Some(read), Some(variant)) = (&op.conditional, &variants[pos]) {
                        self.conditional_read(&op, read, &methods[pos], variant);
                    }
                }
            }
        }
        let streams: Vec<&EventStream> = self
            .streams
            .iter()
            .filter(|s| indices.contains(&s.list))
            .collect();
        let method_of = |op: usize| {
            let pos = indices.iter().position(|&i| i == op).expect("same manager");
            methods[pos].clone()
        };
        for stream in &streams {
            assert!(
                !used.iter().any(|m| m == "stream"),
                "{key}: the manager already has a `stream` method for the event stream"
            );
            self.stream_method(stream, ty, &method_of(stream.list));
        }
        for exchange in self
            .exchanges
            .iter()
            .filter(|e| indices.contains(&e.operation))
        {
            assert!(
                !used.iter().any(|m| m == "downscope_token"),
                "{key}: the manager already has a `downscope_token` method for the token exchange"
            );
            self.downscope_token(exchange, &method_of(exchange.operation));
        }
        for zip in self.zips.iter().filter(|z| indices.contains(&z.create)) {
            assert!(
                !used.iter().any(|m| m == "download_zip"),
                "{key}: the manager already has a `download_zip` method for the zip download"
            );
            self.download_zip(zip, &method_of(zip.create), &method_of(zip.content));
        }
        for source in self
            .representations
            .iter()
            .filter(|r| indices.contains(&r.operation))
        {
            assert!(
                !used.iter().any(|m| m == "get_representation_content"),
                "{key}: the manager already has a `get_representation_content` method"
            );
            self.representation_content(source);
        }
        self.body.push_str("}\n");
        for stream in &streams {
            self.stream_source(
                stream,
                ty,
                &method_of(stream.list),
                &method_of(stream.options),
            );
        }
    }

    /// `download_zip`: create the archive with this manager's typed `POST`, then
    /// stream the `download_url` Box answers with, as returned.
    fn download_zip(&mut self, zip: &ZipDownload, create: &str, content: &str) {
        let op = &self.program.operations[zip.create];
        let request = op
            .request
            .as_ref()
            .expect("synth: a zip download's POST has a body");
        let body = self.rust_type(unwrap_optionality(&request.ty));
        let url = field_ident(zip.download_url.name.as_str());
        let _ = writeln!(
            self.body,
            "\n    /// Pack the items in `body` into one zip archive ([`Self::{create}`]) and\n\
             \x20   /// stream it from the download URL Box answers with, through this session\n\
             \x20   /// (auth, retries, As-User). [`Self::{content}`] fetches the same archive by\n\
             \x20   /// id."
        );
        self.signature(
            "pub ",
            "download_zip",
            &["&self".to_string(), format!("body: {body}")],
            &format!("Result<{RUNTIME}::Stream, Error>"),
        );
        let _ = writeln!(
            self.body,
            "        let zip = self.{create}(body).await?;\n\
             \x20       let url = zip\n\
             \x20           .{url}\n\
             \x20           .ok_or_else(|| Error::new(\"box: the zip download has no download_url\"))?;\n\
             \x20       let req = self.session.new_request(\"GET\", &url);\n\
             \x20       let resp = self.session.fetch(req).await?;\n\
             \x20       Ok({RUNTIME}::response_stream(&resp))\n\
             \x20   }}"
        );
    }

    /// `get_representation_content`: Box's representation protocol
    /// (`Client::representation_content`) over this manager's item `GET`.
    fn representation_content(&mut self, source: &gantry_synth::Representation) {
        let op = self.program.operations[source.operation].clone();
        let _ = writeln!(
            self.body,
            "\n    /// Download a representation of the item — a PDF, its extracted text, page\n\
             \x20   /// images. `rep_hints` names it as `X-Rep-Hints` does (`\"[pdf]\"`,\n\
             \x20   /// `\"[extracted_text]\"`, `\"[jpg?dimensions=320x320]\"`); `asset_path` picks\n\
             \x20   /// one asset of a multi-asset representation (`\"1.png\"`) and is `\"\"` for a\n\
             \x20   /// single-file one. It waits while Box generates the representation, up to\n\
             \x20   /// `max_wait` ([`{RUNTIME}::DEFAULT_REPRESENTATION_WAIT`] when `None`)."
        );
        let mut params = vec!["&self".to_string()];
        for param in op
            .params
            .iter()
            .filter(|p| p.location == ir::ParamLocation::Path)
        {
            params.push(format!(
                "{}: {}",
                field_ident(param.name.as_str()),
                self.rust_type(&param.ty)
            ));
        }
        params.extend([
            "rep_hints: &str".to_string(),
            "asset_path: &str".to_string(),
            "max_wait: Option<std::time::Duration>".to_string(),
        ]);
        self.signature(
            "pub ",
            "get_representation_content",
            &params,
            &format!("Result<{RUNTIME}::Stream, Error>"),
        );
        self.url_and_request(&op);
        let (fields, hints, field) = (
            &source.fields_param.wire_name,
            &source.hints_param.wire_name,
            &source.field.wire_name,
        );
        let _ = writeln!(
            self.body,
            "        let req = self.session.new_request(\"GET\", &url);\n\
             \x20       let req = {RUNTIME}::with_query(req, {fields:?}, {field:?});\n\
             \x20       let req = {RUNTIME}::with_header(req, {hints:?}, rep_hints);\n\
             \x20       self.session\n\
             \x20           .representation_content(req, {field:?}, asset_path, max_wait)\n\
             \x20           .await\n\
             \x20   }}"
        );
    }

    /// `downscope_token`: Box's token exchange over this manager's typed token
    /// method, restricting the session's current access token. Local type
    /// aliases keep every line short, so the output is rustfmt-clean.
    fn downscope_token(&mut self, exchange: &TokenExchange, method: &str) {
        let op = &self.program.operations[exchange.operation];
        let ir::ResponseShape::Json(ty) = &op.response else {
            unreachable!("synth: a token exchange answers JSON");
        };
        let ret = self.rust_type(unwrap_optionality(ty));
        let body = self.rust_type(&ir::Type::Decl(exchange.body));
        let grant = self.rust_type(&ir::Type::Decl(exchange.grant_type_enum));
        let token_type = self.rust_type(&ir::Type::Decl(exchange.subject_token_type_enum));
        let field = |f: &ir::Field| field_ident(f.name.as_str());
        let (grant_field, subject, subject_type, scope, resource, shared_link) = (
            field(&exchange.grant_type),
            field(&exchange.subject_token),
            field(&exchange.subject_token_type),
            field(&exchange.scope),
            field(&exchange.resource),
            field(&exchange.shared_link),
        );
        let _ = writeln!(
            self.body,
            "\n    /// Exchange the session's current access token for one limited to `scopes`\n\
             \x20   /// and, when given, to one item (`resource`: its API URL, e.g.\n\
             \x20   /// `https://api.box.com/2.0/files/123`) or a shared link. The result is a\n\
             \x20   /// plain access token with no refresh token: build a client from it with\n\
             \x20   /// [`{RUNTIME}::Auth::developer_token`]."
        );
        self.signature(
            "pub ",
            "downscope_token",
            &[
                "&self".to_string(),
                "scopes: &[&str]".to_string(),
                "resource: Option<&str>".to_string(),
                "shared_link: Option<&str>".to_string(),
            ],
            &format!("Result<{ret}, Error>"),
        );
        // `use … as` (a type alias can't construct a tuple struct), sorted by
        // path as rustfmt orders consecutive imports.
        let mut imports = [(body, "Body"), (grant, "Grant"), (token_type, "TokenType")];
        imports.sort();
        for (path, alias) in &imports {
            let _ = writeln!(self.body, "        use {path} as {alias};");
        }
        let _ = writeln!(
            self.body,
            "        let exchange = {TOKEN_EXCHANGE_GRANT:?}.to_string();\n\
             \x20       let access_token = {ACCESS_TOKEN_TYPE:?}.to_string();\n\
             \x20       let body = Body {{\n\
             \x20           {grant_field}: Grant(exchange),\n\
             \x20           {subject}: Some(self.session.access_token().await?),\n\
             \x20           {subject_type}: Some(TokenType(access_token)),\n\
             \x20           {scope}: Some(scopes.join(\" \")),\n\
             \x20           {resource}: resource.map(str::to_string),\n\
             \x20           {shared_link}: shared_link.map(str::to_string),\n\
             \x20           ..Default::default()\n\
             \x20       }};\n\
             \x20       self.{method}(body).await\n\
             \x20   }}"
        );
    }

    /// `stream`: Box's long-poll event stream ([`runtime::EventStream`]) over
    /// this manager's typed page and server methods. Emitted rustfmt-clean.
    fn stream_method(&mut self, stream: &EventStream, ty: &str, list: &str) {
        let list_op = &self.program.operations[stream.list];
        let options_ty = options_type(list_op.manager.as_str(), list);
        let position = field_ident(stream.position_param.name.as_str());
        let _ = writeln!(
            self.body,
            "\n    /// Box's long-poll event stream from `opts.{position}` (`\"now\"` when\n\
             \x20   /// unset): [`{RUNTIME}::EventStream::next`] yields each event once, then\n\
             \x20   /// waits on a real-time server for the next change. Drop the stream to\n\
             \x20   /// stop it."
        );
        // A named source type (not `impl EventSource`) keeps the signature short
        // and lets callers name the stream's type.
        let ret = format!("{RUNTIME}::EventStream<{ty}StreamSource>");
        let one_line = format!("    pub fn stream(&self, opts: Option<{options_ty}>) -> {ret} {{");
        if one_line.len() <= 100 {
            let _ = writeln!(self.body, "{one_line}");
        } else {
            let _ = writeln!(
                self.body,
                "    pub fn stream(\n        &self,\n        opts: Option<{options_ty}>,\n    ) -> {ret} {{"
            );
        }
        let _ = writeln!(
            self.body,
            "        let opts = opts.unwrap_or_default();\n\
             \x20       let position = match &opts.{position} {{\n\
             \x20           Some(position) => position.clone(),\n\
             \x20           None => \"now\".to_string(),\n\
             \x20       }};\n\
             \x20       let source = {ty}StreamSource {{\n\
             \x20           manager: Self::new(self.session.clone()),\n\
             \x20           opts,\n\
             \x20       }};\n\
             \x20       {RUNTIME}::EventStream::new(self.session.clone(), position, source)\n\
             \x20   }}"
        );
    }

    /// The [`runtime::EventSource`] `stream` drives. Emitted rustfmt-clean.
    fn stream_source(&mut self, stream: &EventStream, ty: &str, list: &str, options: &str) {
        let list_op = &self.program.operations[stream.list];
        let options_ty = options_type(list_op.manager.as_str(), list);
        let event = self.rust_type(&ir::Type::Decl(stream.event));
        let field = |f: &ir::Field| field_ident(f.name.as_str());
        let next = field(&stream.next_position);
        let next_value = match stream.position {
            PositionShape::String => format!("page.{next}"),
            PositionShape::StringOrInteger => {
                // Vertical: rustfmt's chain width is exceeded either way.
                format!(
                    "page\n            .{next}\n            .and_then(|p| {RUNTIME}::stream_position(&p.0))"
                )
            }
        };
        let _ = writeln!(
            self.body,
            "\n/// The typed calls [`{ty}::stream`] drives: an [`{RUNTIME}::EventSource`]\n\
             /// over the manager's page and server methods.\n\
             pub struct {ty}StreamSource {{\n\
             \x20   manager: {ty},\n\
             \x20   opts: {options_ty},\n\
             }}\n\n\
             impl {RUNTIME}::EventSource for {ty}StreamSource {{\n\
             \x20   type Event = {event};\n\n\
             \x20   async fn server(&self) -> Result<Option<{RUNTIME}::LongPollServer>, Error> {{\n\
             \x20       let listed = self.manager.{options}().await?;\n\
             \x20       let servers = listed.{servers}.unwrap_or_default();\n\
             \x20       Ok(servers.into_iter().find_map(|s| {{\n\
             \x20           let timeout = s.{timeout}.and_then(|t| u64::try_from(t).ok());\n\
             \x20           Some({RUNTIME}::LongPollServer {{\n\
             \x20               url: s.{url}?,\n\
             \x20               max_retries: s.{retries}.and_then(|n| n.parse().ok()),\n\
             \x20               retry_timeout: timeout.map(std::time::Duration::from_secs),\n\
             \x20           }})\n\
             \x20       }}))\n\
             \x20   }}\n\n\
             \x20   async fn page(&self, position: &str) -> Result<(Vec<Self::Event>, Option<String>), Error> {{\n\
             \x20       let mut opts = self.opts.clone();\n\
             \x20       opts.{position} = Some(position.to_string());\n\
             \x20       let page = self.manager.{list}(Some(opts)).await?;\n\
             \x20       let next = {next_value};\n\
             \x20       Ok((page.{entries}.unwrap_or_default(), next))\n\
             \x20   }}\n\n\
             \x20   fn id(event: &Self::Event) -> Option<&str> {{\n\
             \x20       event.{id}.as_deref()\n\
             \x20   }}\n\
             }}",
            position = field_ident(stream.position_param.name.as_str()),
            servers = field(&stream.servers),
            url = field(&stream.url),
            retries = field(&stream.max_retries),
            timeout = field(&stream.retry_timeout),
            entries = field(&stream.entries),
            id = field(&stream.event_id),
        );
    }

    /// Resolve everything needed to synthesize a paginator for `op`, or `None`
    /// when the cursor shape is not one we generate (the plain method still
    /// ships — a documented fallback, VR-6, never wrong code).
    fn pagination_plan(
        &self,
        op: &ir::Operation,
        name: &ManagerName,
        method: &str,
        paged: &PagedOperation,
    ) -> Option<PaginationPlan> {
        // The response envelope (a struct) carries `entries` + the cursor field.
        let ir::ResponseShape::Json(response_ty) = &op.response else {
            return None;
        };
        let ir::DeclKind::Struct(envelope) = &self.program.decl(decl_of(response_ty)?).kind else {
            return None;
        };
        let field_ty = |wire: &str| envelope.fields.iter().find(|f| f.wire_name == wire);
        let entries = field_ty(&paged.entries_wire)?;
        let cursor = field_ty(&paged.cursor_wire)?;

        // The cursor query parameter (detection guaranteed it is optional).
        let cursor_param = op
            .params
            .iter()
            .find(|p| p.location == ir::ParamLocation::Query && p.wire_name == paged.param_wire)?;
        let param_field = field_ident(cursor_param.name.as_str());

        let efield = field_ident(&snake(&paged.entries_wire));
        let entries_vec = match option_layers(&entries.ty) {
            0 => format!("page.{efield}"),
            1 => format!("page.{efield}.unwrap_or_default()"),
            _ => format!("page.{efield}.flatten().unwrap_or_default()"),
        };

        let advance = match paged.style {
            PageStyle::Marker => {
                // The request marker is a string; the response cursor may be a
                // string or an int (converted). Anything else: skip.
                if !matches!(unwrap_optionality(&cursor_param.ty), ir::Type::String) {
                    return None;
                }
                let cfield = field_ident(&snake(&paged.cursor_wire));
                let cursor_opt = match option_layers(&cursor.ty) {
                    0 => format!("Some(page.{cfield})"),
                    1 => format!("page.{cfield}"),
                    _ => format!("page.{cfield}.flatten()"),
                };
                let arm = match unwrap_optionality(&cursor.ty) {
                    ir::Type::String => {
                        format!(
                            "Some(cursor) if !cursor.is_empty() => self.options.{param_field} = Some(cursor),"
                        )
                    }
                    ir::Type::Int64 => {
                        format!(
                            "Some(cursor) => self.options.{param_field} = Some(cursor.to_string()),"
                        )
                    }
                    // A non-string/int marker cursor is a shape we don't
                    // synthesize — skip the paginator (NF-1: no wildcard).
                    ir::Type::Bool
                    | ir::Type::Float64
                    | ir::Type::Date
                    | ir::Type::DateTime
                    | ir::Type::Binary
                    | ir::Type::JsonValue
                    | ir::Type::List(_)
                    | ir::Type::Map(_)
                    | ir::Type::Decl(_)
                    | ir::Type::Optional(_)
                    | ir::Type::Nullable(_) => return None,
                };
                format!(
                    "            self.buffer = {entries_vec}.into_iter();\n\
                     \x20           match {cursor_opt} {{\n\
                     \x20               {arm}\n\
                     \x20               _ => self.done = true,\n\
                     \x20           }}\n"
                )
            }
            PageStyle::Offset => {
                if !matches!(unwrap_optionality(&cursor_param.ty), ir::Type::Int64) {
                    return None;
                }
                format!(
                    "            let items = {entries_vec};\n\
                     \x20           if items.is_empty() {{\n\
                     \x20               self.done = true;\n\
                     \x20           }} else {{\n\
                     \x20               let next = self.options.{param_field}.unwrap_or(0) + items.len() as i64;\n\
                     \x20               self.options.{param_field} = Some(next);\n\
                     \x20           }}\n\
                     \x20           self.buffer = items.into_iter();\n"
                )
            }
        };

        // Stored fields = the operation's required params (owned), then the body.
        let mut stored: Vec<(String, String)> = op
            .params
            .iter()
            .filter(|p| !matches!(p.ty, ir::Type::Optional(_)))
            .map(|p| (field_ident(p.name.as_str()), self.rust_type(&p.ty)))
            .collect();
        if let Some(body) = &op.request {
            stored.push((
                "body".to_string(),
                self.rust_type(unwrap_optionality(&body.ty)),
            ));
        }
        let mut forward: Vec<String> = stored
            .iter()
            .map(|(field, _)| format!("self.{field}.clone()"))
            .collect();
        forward.push("Some(self.options.clone())".to_string());

        Some(PaginationPlan {
            struct_name: append_without_repeating(
                &format!("{}{}", pascal(op.manager.as_str()), pascal(method)),
                "Paginator",
            ),
            manager_ty: name.struct_name.clone(),
            element: self.rust_type(&paged.element),
            options_ty: options_type(op.manager.as_str(), method),
            // Option A: the public `<method>` returns the paginator; the
            // single-page fetch it drives is the private `<method>_page` — a
            // tentative name the caller overwrites with the one already
            // reserved in the manager's dedup pool (#78).
            paginate: method.to_string(),
            method: format!("{method}_page"),
            stored,
            forward,
            advance,
        })
    }

    /// Emit the module-level paginator struct + its async `next`.
    fn paginator_type(&mut self, plan: &PaginationPlan) {
        let PaginationPlan {
            struct_name,
            manager_ty,
            element,
            options_ty,
            paginate,
            method,
            stored,
            forward,
            advance,
        } = plan;
        // Struct.
        let _ = writeln!(
            self.body,
            "/// Async paginator over [`{manager_ty}::{paginate}`], yielding one \
             `{element}`\n/// per item across pages (FR-7.3).\n\
             pub struct {struct_name} {{\n\
             \x20   manager: {manager_ty},"
        );
        for (field, ty) in stored {
            let _ = writeln!(self.body, "    {field}: {ty},");
        }
        let _ = writeln!(
            self.body,
            "    options: {options_ty},\n\
             \x20   buffer: std::vec::IntoIter<{element}>,\n\
             \x20   done: bool,\n\
             }}\n\n\
             impl {struct_name} {{\n\
             \x20   /// The next item, advancing pages as needed; `None` at the end.\n\
             \x20   /// An error is yielded once, then iteration stops."
        );
        // `next` signature — one line, or rustfmt's `&mut self` wrap past 100.
        let sig =
            format!("    pub async fn next(&mut self) -> Option<Result<{element}, Error>> {{");
        if sig.len() <= 100 {
            let _ = writeln!(self.body, "{sig}");
        } else {
            self.body
                .push_str("    pub async fn next(\n        &mut self,\n");
            let ret = format!("    ) -> Option<Result<{element}, Error>> {{");
            // rustfmt drops the brace when the `) -> … {` line reaches max_width
            // (a 100-col brace line breaks, so require strictly under).
            if ret.len() < 100 {
                let _ = writeln!(self.body, "{ret}");
            } else {
                // rustfmt drops the brace to its own line when the return
                // clause alone overflows.
                let _ = writeln!(self.body, "    ) -> Option<Result<{element}, Error>>");
                self.body.push_str("    {\n");
            }
        }
        self.body.push_str(
            "        loop {\n\
             \x20           if let Some(item) = self.buffer.next() {\n\
             \x20               return Some(Ok(item));\n\
             \x20           }\n\
             \x20           if self.done {\n\
             \x20               return None;\n\
             \x20           }\n",
        );
        // The fetch, then match. rustfmt breaks the `self.manager.m(..).await`
        // chain once it passes `chain_width` (60), then the call's arguments
        // once they pass `fn_call_width` (60) — so mirror both thresholds.
        let joined = forward.join(", ");
        let chain = format!("self.manager.{method}({joined}).await");
        if chain.len() <= 60 {
            let _ = writeln!(self.body, "            let page = match {chain} {{");
        } else {
            self.body
                .push_str("            let page = match self\n                .manager\n");
            let call = format!(".{method}({joined})");
            // Args stay on one line while they fit `fn_call_width` (60) and the
            // whole call line fits `max_width` (100 = 16-space indent + 84).
            if joined.len() <= 60 && call.len() <= 84 {
                let _ = writeln!(self.body, "                {call}");
            } else {
                let _ = writeln!(self.body, "                .{method}(");
                for arg in forward {
                    let _ = writeln!(self.body, "                    {arg},");
                }
                self.body.push_str("                )\n");
            }
            self.body
                .push_str("                .await\n            {\n");
        }
        self.body.push_str(
            "                Ok(page) => page,\n\
             \x20               Err(err) => {\n\
             \x20                   self.done = true;\n\
             \x20                   return Some(Err(err));\n\
             \x20               }\n\
             \x20           };\n",
        );
        self.body.push_str(advance);
        self.body.push_str("        }\n    }\n}\n\n");
    }

    /// Emit the public `<method>` (Option A) inside the manager `impl` — the
    /// paged operation's sole public entry point, returning the paginator.
    fn paginate_method(&mut self, op: &ir::Operation, method: &str, plan: &PaginationPlan) {
        let mut params: Vec<String> = vec!["&self".to_string()];
        for param in op
            .params
            .iter()
            .filter(|p| !matches!(p.ty, ir::Type::Optional(_)))
        {
            params.push(format!(
                "{}: {}",
                field_ident(param.name.as_str()),
                self.rust_type(&param.ty)
            ));
        }
        if let Some(body) = &op.request {
            params.push(format!(
                "body: {}",
                self.rust_type(unwrap_optionality(&body.ty))
            ));
        }
        params.push(format!("opts: Option<{}>", plan.options_ty));

        self.body.push('\n');
        let _ = writeln!(
            self.body,
            "    /// Iterate every `{element}` across pages, threading the cursor.",
            element = plan.element,
        );
        // Constructor signature — inline, or one param per line past 100 cols.
        let sig = format!(
            "    pub fn {method}({}) -> {} {{",
            params.join(", "),
            plan.struct_name,
        );
        if sig.len() <= 100 {
            let _ = writeln!(self.body, "{sig}");
        } else {
            let _ = writeln!(self.body, "    pub fn {method}(");
            for param in &params {
                let line = format!("        {param},");
                if line.len() <= 100 {
                    let _ = writeln!(self.body, "{line}");
                } else if let Some((head, inner)) = param.split_once(": Option<") {
                    // rustfmt breaks an over-long `name: Option<Type>` param.
                    let inner = inner.strip_suffix('>').unwrap_or(inner);
                    let _ = writeln!(self.body, "        {head}: Option<");
                    let _ = writeln!(self.body, "            {inner},");
                    self.body.push_str("        >,\n");
                } else {
                    let _ = writeln!(self.body, "{line}");
                }
            }
            let _ = writeln!(self.body, "    ) -> {} {{", plan.struct_name);
        }
        let _ = writeln!(
            self.body,
            "        {struct_name} {{\n\
             \x20           manager: {manager_ty}::new(self.session.clone()),",
            struct_name = plan.struct_name,
            manager_ty = plan.manager_ty,
        );
        for (field, _) in &plan.stored {
            let _ = writeln!(self.body, "            {field},");
        }
        self.body.push_str(
            "            options: opts.unwrap_or_default(),\n\
             \x20           buffer: Vec::new().into_iter(),\n\
             \x20           done: false,\n\
             \x20       }\n\
             \x20   }\n",
        );
    }

    /// Emit the module-level options struct for an operation's optional params.
    fn options_struct(&mut self, op: &ir::Operation, manager_ty: &str, method: &str) {
        let optional: Vec<&ir::Param> = op
            .params
            .iter()
            .filter(|p| matches!(p.ty, ir::Type::Optional(_)))
            .collect();
        if optional.is_empty() {
            return;
        }
        let _ = writeln!(
            self.body,
            "/// Optional parameters for [`{manager_ty}::{method}`].\n\
             #[derive(Clone, Debug, Default)]\n\
             pub struct {opt} {{",
            opt = options_type(op.manager.as_str(), method),
        );
        for param in &optional {
            let inner = unwrap_optionality(&param.ty);
            let _ = writeln!(
                self.body,
                "    pub {field}: Option<{ty}>,",
                field = field_ident(param.name.as_str()),
                ty = self.rust_type(inner),
            );
        }
        self.body.push_str("}\n\n");
    }

    /// One operation → a single-page async method. `method` is the emitted name;
    /// `options_name` is the base for its `Options` type (they differ only for a
    /// paged op, whose single-page fetch is renamed `<method>_page` yet shares
    /// the public method's options struct). When `public_method` is false the
    /// method is module-private — the Option-A paged shape, where the public
    /// `<method>` is the paginator and this fetch is only driven by it.
    fn operation(
        &mut self,
        op: &ir::Operation,
        method: &str,
        options_name: &str,
        public_method: bool,
    ) {
        let mut required: Vec<&ir::Param> = Vec::new();
        let mut optional: Vec<&ir::Param> = Vec::new();
        for param in &op.params {
            if matches!(param.ty, ir::Type::Optional(_)) {
                optional.push(param);
            } else {
                required.push(param);
            }
        }

        let options_ty = options_type(op.manager.as_str(), options_name);
        // Signature.
        let mut params: Vec<String> = vec!["&self".to_string()];
        for param in &required {
            params.push(format!(
                "{}: {}",
                field_ident(param.name.as_str()),
                self.rust_type(&param.ty)
            ));
        }
        if let Some(body) = &op.request {
            params.push(format!(
                "body: {}",
                self.rust_type(unwrap_optionality(&body.ty))
            ));
        }
        if !optional.is_empty() {
            params.push(format!("opts: Option<{options_ty}>"));
        }
        let ret = self.return_type(op);

        self.body.push('\n');
        let vis = if public_method { "pub " } else { "" };
        self.signature(vis, method, &params, &ret);

        self.url_and_request(op);
        let modifies = op
            .params
            .iter()
            .any(|p| p.location != ir::ParamLocation::Path)
            || op.request.is_some()
            // A versioned op reassigns `req` to set the `box-version` header.
            || self.is_versioned(op);
        let req_binding = if modifies { "let mut req" } else { "let req" };
        let _ = writeln!(
            self.body,
            "        {req_binding} = self.session.new_request({method_str:?}, &url);",
            method_str = http_method(op.method),
        );
        self.apply_params(&required, false);
        if !optional.is_empty() {
            self.body
                .push_str("        let opts = opts.unwrap_or_default();\n");
            self.apply_params(&optional, true);
        }
        self.version_header(op);
        self.request_body(op);
        self.fetch_and_decode(op);
        self.body.push_str("    }\n");
    }

    /// An async method's signature line(s), wrapped the way rustfmt does past
    /// 100 columns so the output stays `cargo fmt`-clean (TR-Rust.4).
    fn signature(&mut self, vis: &str, method: &str, params: &[String], ret: &str) {
        let sig = format!(
            "    {vis}async fn {method}({}) -> {ret} {{",
            params.join(", ")
        );
        if sig.len() <= 100 {
            let _ = writeln!(self.body, "{sig}");
            return;
        }
        let _ = writeln!(self.body, "    {vis}async fn {method}(");
        for param in params {
            let line = format!("        {param},");
            if line.len() <= 100 {
                let _ = writeln!(self.body, "{line}");
            } else if let Some((head, inner)) = param.split_once(": Option<") {
                // rustfmt breaks an over-long `name: Option<Type>` param.
                let inner = inner.strip_suffix('>').unwrap_or(inner);
                let _ = writeln!(self.body, "        {head}: Option<");
                let _ = writeln!(self.body, "            {inner},");
                self.body.push_str("        >,\n");
            } else {
                let _ = writeln!(self.body, "{line}");
            }
        }
        let _ = writeln!(self.body, "    ) -> {ret} {{");
    }

    /// A conditional read's `<method>_if_modified` (Box's etag flow):
    /// `<method>` with the `If-None-Match` parameter set to `etag`, answering
    /// `Ok(None)` for the 304 Not Modified that means "unchanged since etag"
    /// instead of an `Err`. Lowering only marks JSON reads conditional.
    fn conditional_read(
        &mut self,
        op: &ir::Operation,
        read: &ir::ConditionalRead,
        base: &str,
        variant: &str,
    ) {
        let ir::ResponseShape::Json(ty) = &op.response else {
            unreachable!("sema: a conditional read returns JSON");
        };
        let ok = self.rust_type(unwrap_optionality(ty));
        let options_ty = options_type(op.manager.as_str(), base);
        let etag_optional = op
            .params
            .iter()
            .any(|p| p.name == read.etag && matches!(p.ty, ir::Type::Optional(_)));
        // The base signature with the etag lifted out as a required `String`.
        let mut params = vec!["&self".to_string()];
        let mut call: Vec<String> = Vec::new();
        for param in op
            .params
            .iter()
            .filter(|p| !matches!(p.ty, ir::Type::Optional(_)))
        {
            if param.name == read.etag {
                call.push("etag".to_string());
                continue;
            }
            let name = field_ident(param.name.as_str());
            params.push(format!("{name}: {}", self.rust_type(&param.ty)));
            call.push(name);
        }
        params.push("etag: String".to_string());
        if let Some(body) = &op.request {
            params.push(format!(
                "body: {}",
                self.rust_type(unwrap_optionality(&body.ty))
            ));
            call.push("body".to_string());
        }
        let has_options = op
            .params
            .iter()
            .any(|p| matches!(p.ty, ir::Type::Optional(_)));
        if has_options {
            params.push(format!("opts: Option<{options_ty}>"));
            call.push(if etag_optional { "Some(opts)" } else { "opts" }.to_string());
        }
        let _ = writeln!(
            self.body,
            "\n    /// [`Self::{base}`] with `If-None-Match` set to `etag`: `Ok(None)` when\n\
             \x20   /// the item is unchanged since `etag` (Box answers 304 Not Modified)."
        );
        self.signature(
            "pub ",
            variant,
            &params,
            &format!("Result<Option<{ok}>, Error>"),
        );
        if etag_optional {
            let field = field_ident(read.etag.as_str());
            let _ = writeln!(
                self.body,
                "        let mut opts = opts.unwrap_or_default();\n\
                 \x20       opts.{field} = Some(etag);"
            );
        }
        let _ = writeln!(
            self.body,
            "        match self.{base}({}).await {{\n\
             \x20           Err(err) if err.status() == Some(304) => Ok(None),\n\
             \x20           result => result.map(Some),\n\
             \x20       }}\n\
             \x20   }}",
            call.join(", ")
        );
    }

    /// Build the URL from the D-106 base class + structured path segments.
    fn url_and_request(&mut self, op: &ir::Operation) {
        let base = base_class(op.base_url);
        if op.path.is_empty() {
            let _ = writeln!(
                self.body,
                "        let url = self.session.base_url({base:?});"
            );
            return;
        }
        let _ = writeln!(
            self.body,
            "        let mut url = self.session.base_url({base:?});"
        );
        for segment in &op.path {
            match segment {
                ir::PathSegment::Literal(text) => {
                    // Debug-escape so a `"` or `\` in the literal stays valid
                    // string content, never altering the generated source.
                    let _ = writeln!(self.body, "        url.push_str({:?});", format!("/{text}"));
                }
                ir::PathSegment::Parameter(name) => {
                    let value = self.path_value(op, name);
                    self.body.push_str("        url.push('/');\n");
                    self.emit_path_push(&value);
                }
                ir::PathSegment::Composite(parts) => {
                    self.body.push_str("        url.push('/');\n");
                    for part in parts {
                        match part {
                            ir::PathPart::Literal(text) => {
                                let _ = writeln!(self.body, "        url.push_str({text:?});");
                            }
                            ir::PathPart::Parameter(name) => {
                                let value = self.path_value(op, name);
                                self.emit_path_push(&value);
                            }
                        }
                    }
                }
            }
        }
    }

    /// Emit a percent-escaped path segment. The value binds to a local first so
    /// the nested `push_str(&path_escape(…))` call never trips rustfmt's
    /// call-width wrapping (unpredictable from line length alone).
    fn emit_path_push(&mut self, value: &str) {
        self.uses_path_escape = true;
        let _ = writeln!(self.body, "        let seg = path_escape(&{value});");
        self.body.push_str("        url.push_str(&seg);\n");
    }

    /// The Rust expression (a `String`/`&str`) for a path parameter's value.
    fn path_value(&self, op: &ir::Operation, name: &ir::Identifier) -> String {
        let param = op
            .params
            .iter()
            .find(|p| p.location == ir::ParamLocation::Path && p.name == *name)
            .expect("ingestion validated every path placeholder");
        self.string_value(&field_ident(param.name.as_str()), &param.ty)
    }

    /// Emit `with_query`/`with_header` calls. When `from_options`, values come
    /// from the moved-out options struct field.
    fn apply_params(&mut self, params: &[&ir::Param], from_options: bool) {
        for param in params {
            let call = match param.location {
                ir::ParamLocation::Query => "with_query",
                ir::ParamLocation::Header => "with_header",
                ir::ParamLocation::Path => continue,
            };
            let wire = format!("{:?}", param.wire_name);
            if from_options {
                let inner = unwrap_optionality(&param.ty);
                let value = self.string_value("value", inner);
                let _ = writeln!(
                    self.body,
                    "        if let Some(value) = opts.{field} {{",
                    field = field_ident(param.name.as_str()),
                );
                self.emit_with_call("            ", call, &wire, &value);
                self.body.push_str("        }\n");
            } else {
                let value = self.string_value(&field_ident(param.name.as_str()), &param.ty);
                self.emit_with_call("        ", call, &wire, &value);
            }
        }
    }

    /// Whether the operation targets a non-base API version (so it carries the
    /// `box-version` header).
    fn is_versioned(&self, op: &ir::Operation) -> bool {
        op.api_version.is_some() && op.api_version.as_ref() != self.base_version.as_ref()
    }

    /// Set the `box-version` header for a non-base operation (D-191). The header
    /// is a required constant equal to the operation's API version, so the engine
    /// sends it automatically rather than exposing it as a parameter.
    fn version_header(&mut self, op: &ir::Operation) {
        if self.is_versioned(op)
            && let Some(version) = &op.api_version
        {
            let _ = writeln!(
                self.body,
                "        req = runtime::with_header(req, \"box-version\", {:?});",
                version.0
            );
        }
    }

    /// Emit `req = runtime::<call>(req, <wire>, &<value>);`, binding the value
    /// to a local first when the inline form would overflow 100 columns.
    fn emit_with_call(&mut self, indent: &str, call: &str, wire: &str, value: &str) {
        let inline = format!("{indent}req = runtime::{call}(req, {wire}, &{value});");
        if inline.len() <= 100 {
            let _ = writeln!(self.body, "{inline}");
        } else {
            let _ = writeln!(self.body, "{indent}let arg = {value};");
            let _ = writeln!(
                self.body,
                "{indent}req = runtime::{call}(req, {wire}, &arg);"
            );
        }
    }

    fn request_body(&mut self, op: &ir::Operation) {
        let Some(body) = &op.request else {
            return;
        };
        match body.media {
            ir::RequestMedia::Json | ir::RequestMedia::JsonPatch => {
                self.body.push_str(
                    "        let payload = serde_json::to_vec(&body)?;\n\
                     \x20       req = runtime::with_json_body(req, &payload);\n",
                );
            }
            // An octet-stream body sends the caller's `Vec<u8>` bytes: the
            // runtime buffers every body for retry replay anyway, so it hands
            // them straight to a `Stream`, matching Go's
            // `WithStreamBody(req, body, …)`. This is the wire the chunked
            // upload part PUT rides on.
            ir::RequestMedia::OctetStream => {
                // Pre-wrapped to rustfmt's 100-col layout (the generated crate is
                // `cargo fmt --check`-clean by construction, TR-Rust.4).
                self.body.push_str(
                    "        req = runtime::with_stream_body(\n\
                     \x20           req,\n\
                     \x20           runtime::Stream::from_bytes(body),\n\
                     \x20           \"application/octet-stream\",\n\
                     \x20       );\n",
                );
            }
            // Which field is the binary part vs. the JSON part is structural
            // (G-7), never a hardcoded field name.
            ir::RequestMedia::Multipart => {
                let shape =
                    ir::classify_multipart(self.program, &body.ty).unwrap_or_else(|detail| {
                        panic!("rust backend cannot express multipart body: {detail} — engine bug")
                    });
                let (json_expr, json_wire) = match shape.json_field {
                    Some(field) => {
                        let _ = writeln!(
                            self.body,
                            "        let json_bytes = serde_json::to_vec(&body.{})?;",
                            field_ident(field.name.as_str())
                        );
                        ("json_bytes".to_string(), field.wire_name.clone())
                    }
                    None => ("Vec::new()".to_string(), String::new()),
                };
                let (file_expr, file_wire) = match shape.binary_field {
                    Some(field) => (
                        format!(
                            "runtime::Stream::from_bytes(body.{})",
                            field_ident(field.name.as_str())
                        ),
                        field.wire_name.clone(),
                    ),
                    None => ("runtime::Stream::empty()".to_string(), String::new()),
                };
                let inline = format!(
                    "        req = runtime::with_multipart_body(req, {json_wire:?}, &{json_expr}, {file_wire:?}, {file_expr});"
                );
                if inline.len() <= 100 {
                    let _ = writeln!(self.body, "{inline}");
                } else {
                    let _ = writeln!(
                        self.body,
                        "        req = runtime::with_multipart_body(\n\
                         \x20           req,\n\
                         \x20           {json_wire:?},\n\
                         \x20           &{json_expr},\n\
                         \x20           {file_wire:?},\n\
                         \x20           {file_expr},\n\
                         \x20       );"
                    );
                }
            }
            ir::RequestMedia::UrlEncoded => self.url_encoded_body(body),
        }
    }

    /// Form-encode the body struct's fields (the OAuth2 token endpoints), rather
    /// than sending JSON bytes under a form content type. Mirrors the Go
    /// backend's `url.Values` assembly.
    fn url_encoded_body(&mut self, body: &ir::RequestBody) {
        let ir::Type::Decl(id) = unwrap_optionality(&body.ty) else {
            // A non-struct url-encoded body is not something the Box specs
            // produce; fall back to raw JSON bytes rather than emit nothing.
            self.body.push_str(
                "        let payload = serde_json::to_vec(&body)?;\n\
                 \x20       req = runtime::with_form_body(req, &payload);\n",
            );
            return;
        };
        let ir::DeclKind::Struct(s) = &self.program.decl(*id).kind else {
            self.body.push_str(
                "        let payload = serde_json::to_vec(&body)?;\n\
                 \x20       req = runtime::with_form_body(req, &payload);\n",
            );
            return;
        };
        let optional: Vec<&ir::Field> = s
            .fields
            .iter()
            .filter(|f| matches!(f.ty, ir::Type::Optional(_) | ir::Type::Nullable(_)))
            .collect();
        // Required fields seed a `vec![]` literal (clippy dislikes
        // `Vec::new()` followed by unconditional `push`es); optional fields
        // push conditionally.
        let entries: Vec<String> = s
            .fields
            .iter()
            .filter(|f| !matches!(f.ty, ir::Type::Optional(_) | ir::Type::Nullable(_)))
            .map(|f| {
                let value =
                    self.form_value(&format!("body.{}", field_ident(f.name.as_str())), &f.ty);
                format!("({:?}, {value})", f.wire_name)
            })
            .collect();
        let kw = if optional.is_empty() { "" } else { "mut " };
        if entries.is_empty() {
            let _ = writeln!(
                self.body,
                "        let {kw}form: Vec<(&str, String)> = Vec::new();"
            );
        } else {
            let single = format!(
                "        let {kw}form: Vec<(&str, String)> = vec![{}];",
                entries.join(", ")
            );
            if single.len() <= 100 {
                let _ = writeln!(self.body, "{single}");
            } else {
                let _ = writeln!(
                    self.body,
                    "        let {kw}form: Vec<(&str, String)> = vec!["
                );
                for entry in &entries {
                    let _ = writeln!(self.body, "            {entry},");
                }
                self.body.push_str("        ];\n");
            }
        }
        for field in &optional {
            let inner = unwrap_optionality(&field.ty);
            let value = self.form_value("value", inner);
            let _ = writeln!(
                self.body,
                "        if let Some(value) = &body.{field} {{\n\
                 \x20           form.push(({wire:?}, {value}));\n\
                 \x20       }}",
                field = field_ident(field.name.as_str()),
                wire = field.wire_name,
            );
        }
        self.body.push_str(
            "        let payload = crate::internal::form_encode(&form);\n\
             \x20       req = runtime::with_form_body(req, payload.as_bytes());\n",
        );
    }

    /// An owned-`String` expression for a form field value, given `expr` typed
    /// `&T` (or a value place for required fields).
    fn form_value(&self, expr: &str, ty: &ir::Type) -> String {
        match ty {
            ir::Type::String | ir::Type::Date | ir::Type::DateTime => format!("{expr}.clone()"),
            ir::Type::Bool | ir::Type::Int64 | ir::Type::Float64 => format!("{expr}.to_string()"),
            ir::Type::Decl(id) => match &self.program.decl(*id).kind {
                ir::DeclKind::Enum(e) if matches!(e.extensibility, ir::Extensibility::Open) => {
                    format!("{expr}.0.clone()")
                }
                ir::DeclKind::Alias(inner) => {
                    let inner = inner.clone();
                    self.form_value(expr, &inner)
                }
                ir::DeclKind::Enum(_) | ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => {
                    format!("serde_json::to_string({expr}).unwrap_or_default()")
                }
            },
            ir::Type::Binary
            | ir::Type::JsonValue
            | ir::Type::List(_)
            | ir::Type::Map(_)
            | ir::Type::Optional(_)
            | ir::Type::Nullable(_) => format!("serde_json::to_string({expr}).unwrap_or_default()"),
        }
    }

    fn fetch_and_decode(&mut self, op: &ir::Operation) {
        match &op.response {
            ir::ResponseShape::None => {
                self.body
                    .push_str("        let _ = self.session.fetch(req).await?;\n        Ok(())\n");
            }
            ir::ResponseShape::Json(_) => {
                self.body.push_str(
                    "        let resp = self.session.fetch(req).await?;\n\
                     \x20       let data = runtime::response_bytes(&resp)?;\n\
                     \x20       Ok(serde_json::from_slice(&data)?)\n",
                );
            }
            ir::ResponseShape::Binary => {
                self.body.push_str(
                    "        let resp = self.session.fetch(req).await?;\n\
                     \x20       Ok(runtime::response_stream(&resp))\n",
                );
            }
            ir::ResponseShape::Text => {
                self.body.push_str(
                    "        let resp = self.session.fetch(req).await?;\n\
                     \x20       let data = runtime::response_bytes(&resp)?;\n\
                     \x20       Ok(String::from_utf8_lossy(&data).into_owned())\n",
                );
            }
            ir::ResponseShape::Redirect => {
                self.body.push_str(
                    "        let resp = self.session.fetch(req).await?;\n\
                     \x20       Ok(runtime::response_header(&resp, \"Location\"))\n",
                );
            }
        }
    }

    fn return_type(&self, op: &ir::Operation) -> String {
        let ok = match &op.response {
            ir::ResponseShape::None => "()".to_string(),
            ir::ResponseShape::Json(ty) => self.rust_type(unwrap_optionality(ty)),
            ir::ResponseShape::Binary => format!("{RUNTIME}::Stream"),
            ir::ResponseShape::Text | ir::ResponseShape::Redirect => "String".to_string(),
        };
        format!("Result<{ok}, Error>")
    }

    /// A Rust expression (typed `String` or `&str`) converting `expr` (already
    /// non-optional) into the string a query/header/path slot needs.
    fn string_value(&self, expr: &str, ty: &ir::Type) -> String {
        match ty {
            ir::Type::String | ir::Type::Date | ir::Type::DateTime => expr.to_string(),
            ir::Type::Bool | ir::Type::Int64 | ir::Type::Float64 => format!("{expr}.to_string()"),
            ir::Type::List(inner) if matches!(**inner, ir::Type::String) => {
                format!("{expr}.join(\",\")")
            }
            ir::Type::List(inner) if is_scalar(self.program, inner) => {
                // Routed through a helper so the call site stays a short chain
                // (rustfmt breaks any chain wider than `chain_width`).
                format!(
                    "crate::internal::join(&{expr}, |v| {})",
                    self.list_element(inner)
                )
            }
            ir::Type::Decl(id) => match &self.program.decl(*id).kind {
                ir::DeclKind::Enum(e) if matches!(e.extensibility, ir::Extensibility::Open) => {
                    format!("{expr}.0")
                }
                ir::DeclKind::Alias(inner) => {
                    let inner = inner.clone();
                    self.string_value(expr, &inner)
                }
                ir::DeclKind::Enum(_) | ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => {
                    json_string(expr)
                }
            },
            ir::Type::List(_)
            | ir::Type::Map(_)
            | ir::Type::JsonValue
            | ir::Type::Binary
            | ir::Type::Optional(_)
            | ir::Type::Nullable(_) => json_string(expr),
        }
    }

    /// The per-element `String` expression for joining a scalar list, in terms
    /// of the iterator variable `v` (a `&Element`).
    fn list_element(&self, inner: &ir::Type) -> String {
        match inner {
            ir::Type::String | ir::Type::Date | ir::Type::DateTime => "v.clone()".to_string(),
            ir::Type::Bool | ir::Type::Int64 | ir::Type::Float64 => "v.to_string()".to_string(),
            ir::Type::Decl(id) => match &self.program.decl(*id).kind {
                ir::DeclKind::Enum(e) if matches!(e.extensibility, ir::Extensibility::Open) => {
                    "v.0.clone()".to_string()
                }
                ir::DeclKind::Alias(inner) => {
                    let inner = inner.clone();
                    self.list_element(&inner)
                }
                ir::DeclKind::Enum(_) | ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => {
                    "serde_json::to_string(v).unwrap_or_default()".to_string()
                }
            },
            ir::Type::Binary
            | ir::Type::JsonValue
            | ir::Type::List(_)
            | ir::Type::Map(_)
            | ir::Type::Optional(_)
            | ir::Type::Nullable(_) => "serde_json::to_string(v).unwrap_or_default()".to_string(),
        }
    }

    /// The Rust type for a value at a manager boundary (param/body/return).
    /// Decls resolve through the shared module registry so manager type paths
    /// agree with the generated model modules (D-149 review).
    fn rust_type(&self, ty: &ir::Type) -> String {
        match ty {
            ir::Type::Bool => "bool".into(),
            ir::Type::Int64 => "i64".into(),
            ir::Type::Float64 => "f64".into(),
            ir::Type::String | ir::Type::Date | ir::Type::DateTime => "String".into(),
            ir::Type::Binary => "Vec<u8>".into(),
            ir::Type::JsonValue => "serde_json::Value".into(),
            ir::Type::List(inner) => format!("Vec<{}>", self.rust_type(inner)),
            ir::Type::Map(inner) => {
                format!(
                    "std::collections::HashMap<String, {}>",
                    self.rust_type(inner)
                )
            }
            ir::Type::Decl(id) => {
                let decl = self.program.decl(*id);
                format!(
                    "crate::models::{}::{}",
                    self.modules[&decl.module],
                    type_name(decl.name.as_str())
                )
            }
            ir::Type::Optional(inner) | ir::Type::Nullable(inner) => {
                format!("Option<{}>", self.rust_type(inner))
            }
        }
    }
}

/// The Rust method name for an operation (snake_case). Versioned/variation
/// operations get suffixed so base and versioned surfaces never collide
/// (FR-7.5).
pub(crate) fn method_name(op: &ir::Operation) -> String {
    let mut name = snake(op.name.as_str());
    if let Some(variation) = &op.variation {
        name.push('_');
        name.push_str(&snake(variation.as_str()));
    }
    // The API version no longer suffixes the name (D-191): the `box-version`
    // header is set automatically per endpoint, and versioned operations live
    // in their own managers so nothing collides.
    // Keyword-safe (raw identifier where needed).
    field_ident(&name)
}

/// The module-level options struct name for an operation (manager-qualified so
/// it stays unique across the `managers` module).
fn options_type(manager: &str, method: &str) -> String {
    append_without_repeating(&format!("{}{}", pascal(manager), pascal(method)), "Options")
}

/// A `String`-producing JSON encode for a complex query value (the Box
/// `mdfilters` convention). Infallible on generated models.
fn json_string(expr: &str) -> String {
    format!("serde_json::to_string(&{expr}).unwrap_or_default()")
}

fn is_scalar(program: &ir::Program, ty: &ir::Type) -> bool {
    match ty {
        ir::Type::String
        | ir::Type::Bool
        | ir::Type::Int64
        | ir::Type::Float64
        | ir::Type::Date
        | ir::Type::DateTime => true,
        ir::Type::Decl(id) => match &program.decl(*id).kind {
            ir::DeclKind::Enum(_) => true,
            ir::DeclKind::Alias(inner) => is_scalar(program, inner),
            ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => false,
        },
        ir::Type::Binary
        | ir::Type::JsonValue
        | ir::Type::List(_)
        | ir::Type::Map(_)
        | ir::Type::Optional(_)
        | ir::Type::Nullable(_) => false,
    }
}

/// Allocate a collision-free name in a scope: `base`, else `base_2`, … —
/// deterministic given a stable iteration order (FR-6.2).
fn dedupe(used: &mut Vec<String>, base: String) -> String {
    let mut candidate = base.clone();
    let mut n = 2;
    while used.contains(&candidate) {
        candidate = format!("{base}_{n}");
        n += 1;
    }
    used.push(candidate.clone());
    candidate
}

fn unwrap_optionality(ty: &ir::Type) -> &ir::Type {
    match ty {
        ir::Type::Optional(inner) | ir::Type::Nullable(inner) => unwrap_optionality(inner),
        ir::Type::Bool
        | ir::Type::Int64
        | ir::Type::Float64
        | ir::Type::String
        | ir::Type::Date
        | ir::Type::DateTime
        | ir::Type::Binary
        | ir::Type::JsonValue
        | ir::Type::List(_)
        | ir::Type::Map(_)
        | ir::Type::Decl(_) => ty,
    }
}

