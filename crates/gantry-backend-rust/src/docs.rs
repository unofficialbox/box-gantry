const PAGINATION_GUIDE: &str = "# Pagination\n\n\
Marker- and offset-paginated list operations return a paginator — the list\n\
method *is* the paginator. You drive it with `.next().await`, which yields one\n\
element at a time and threads the cursor for you:\n\n\
```rust\n\
let mut pages = client.folders.list_items(folder_id, None);\n\
while let Some(item) = pages.next().await {\n\
\x20   let item = item?;\n\
\x20   // use item\n\
}\n\
```\n\n\
The paginator stops when the last page is reached. It owns a copy of the\n\
options you pass, so your value is never mutated.\n\n\
## Events\n\n\
`client.events.stream` follows Box's long-poll event stream: `.next().await`\n\
yields the events after `stream_position` (`\"now\"` when unset), each once — Box\n\
may deliver an event twice — then waits on a real-time server until Box reports\n\
a change. It lists a fresh server when Box asks it to reconnect, and retries a\n\
long poll that times out. A failed call is yielded once and ends the stream;\n\
drop the stream to stop it:\n\n\
```rust\n\
let mut events = client.events.stream(None);\n\
while let Some(event) = events.next().await {\n\
\x20   let event = event?;\n\
\x20   // use event\n\
}\n\
```\n\n\
## Representations (PDF, text, thumbnails)\n\n\
`client.files.get_representation_content` downloads a rendering of a file that\n\
Box generates on demand — a PDF, its extracted text, page images. `rep_hints`\n\
names it as Box's `X-Rep-Hints` header does; `asset_path` picks one asset of a\n\
multi-asset representation (`\"1.png\"` for a page) and is `\"\"` for a single-file\n\
one. It waits while Box generates the representation, up to `max_wait`\n\
(`runtime::DEFAULT_REPRESENTATION_WAIT` when `None`), and returns an error if Box\n\
fails to:\n\n\
```rust\n\
let text = client\n\
\x20   .files\n\
\x20   .get_representation_content(file_id, \"[extracted_text]\", \"\", None)\n\
\x20   .await?;\n\
```\n";

const ERRORS_GUIDE: &str = "# Errors\n\
\n\
Every I/O method returns `Result<T, runtime::Error>`. An `Err` is either a\n\
transport failure or a non-2xx response after the network layer's retries\n\
(exponential backoff + jitter, `401` refresh, `Retry-After`). For a non-2xx\n\
response, `err.status()` is the HTTP status and `err.api()` the\n\
`runtime::ApiError` with Box's error `code`, `message`, and `request_id`\n\
plus the raw `body`; both are `None` for any other failure:\n\
\n\
```rust,ignore\n\
match result {\n\
\x20\x20\x20\x20Err(err) if err.status() == Some(404) => { /* not found */ }\n\
\x20\x20\x20\x20Err(err) => eprintln!(\"{err}\"), // e.g. box: status 403 access_denied: … (request_id …)\n\
\x20\x20\x20\x20Ok(value) => { /* … */ }\n\
}\n\
```\n\
\n\
## Etags: `If-None-Match` and `If-Match`\n\
\n\
Files and folders carry an `etag`. Send it back to stay in sync with Box\n\
(Box's [Ensure consistency](https://developer.box.com/guides/api-calls/ensure-consistency/)\n\
guide):\n\
\n\
- **Reads** — a file, folder, or web link `get`, and each shared-item lookup, has an\n\
\x20\x20`…_if_modified` variant that takes the stored etag, sends it as\n\
\x20\x20`If-None-Match`, and returns `Ok(None)` when Box answers `304 Not Modified`:\n\
\x20\x20keep your cached copy. (The plain method surfaces that 304 as the error\n\
\x20\x20above if you set `if-none-match` on it yourself.)\n\
- **Writes** — pass the etag as `if_match` on a file, folder, or web link update or\n\
\x20\x20delete, or a new file version upload. Box answers `412 Precondition\n\
\x20\x20Failed` (code `precondition_failed`) when the item changed since you read\n\
\x20\x20it, and `err.is_precondition_failed()` reports it: read it again, reapply\n\
\x20\x20your change, retry. `If-Match` can't block a move.\n\
\n\
```rust,ignore\n\
match client.files.get_if_modified(file_id.clone(), etag.clone(), None).await? {\n\
\x20\x20\x20\x20None => { /* unchanged since etag */ }\n\
\x20\x20\x20\x20Some(file) => { /* changed: the current file */ }\n\
}\n\
\n\
// Re-read and retry: the update lands only on the version it was made from.\n\
let mut attempts = 0;\n\
let updated = loop {\n\
\x20\x20\x20\x20attempts += 1;\n\
\x20\x20\x20\x20let guarded = FilesUpdateOptions { if_match: Some(etag.clone()), ..Default::default() };\n\
\x20\x20\x20\x20match client.files.update(file_id.clone(), body.clone(), Some(guarded)).await {\n\
\x20\x20\x20\x20\x20\x20\x20\x20Err(err) if err.is_precondition_failed() && attempts < 3 => {\n\
\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20let current = client.files.get(file_id.clone(), None).await?;\n\
\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20etag = current.etag.flatten().unwrap_or_default(); // reapply your change to current here\n\
\x20\x20\x20\x20\x20\x20\x20\x20}\n\
\x20\x20\x20\x20\x20\x20\x20\x20result => break result?,\n\
\x20\x20\x20\x20}\n\
};\n\
```\n";

/// Webhooks guide: verifying Box's signature on a webhook delivery with the
/// runtime's verifier.
const WEBHOOKS_GUIDE: &str = "# Webhooks\n\
\n\
Once you generate signature keys for your app (Developer Console → **Webhooks**\n\
→ **Manage signature keys**), Box signs every webhook delivery. Each\n\
`BOX-SIGNATURE-PRIMARY` / `BOX-SIGNATURE-SECONDARY` header is the base64\n\
HMAC-SHA256, under that key, of the request body followed by the\n\
`BOX-DELIVERY-TIMESTAMP` header (Box's\n\
[Verify webhook signatures](https://developer.box.com/guides/webhooks/v2/signatures-v2/)\n\
guide). `runtime::WebhookVerifier` checks a delivery before you trust it:\n\
\n\
```rust,ignore\n\
use box_open_sdk::runtime::WebhookVerifier;\n\
\n\
let verifier = WebhookVerifier::new()\n\
\x20\x20\x20\x20.primary_key(primary_key)\n\
\x20\x20\x20\x20.secondary_key(secondary_key);\n\
// `headers`: any (name, value) pairs, e.g. from an `http::HeaderMap`.\n\
let pairs = headers.iter().map(|(k, v)| (k.as_str(), v.to_str().unwrap_or_default()));\n\
if !verifier.verify(&body, pairs) {\n\
\x20\x20\x20\x20// reject: not from Box, altered, or stale\n\
}\n\
```\n\
\n\
- **Pass the body exactly as received.** Parsed and re-serialized JSON won't\n\
\x20\x20verify.\n\
- **Either key may be missing.** A delivery is genuine when the signature of\n\
\x20\x20any configured key matches, so you can rotate one key while the other keeps\n\
\x20\x20verifying.\n\
- **Old or future deliveries are refused.** A delivery stamped more than ten\n\
\x20\x20minutes ago (`max_age`) or in the future fails, which blocks replays.\n\
- **Header names match in any case**, and the comparison takes the same time\n\
\x20\x20wherever a signature differs.\n";

