//! Generated round-trip tests (FR-7.8, VR-4).
//!
//! Inline `#[cfg(test)]` modules that compile *and pass* under `cargo test`,
//! exercising the exact serialization semantics VR-4 names:
//!
//! - **optional presence / absence / explicit-null** — the D-110 tri-state
//!   through `serde_helpers::double_option` (absent → omitted, present-null →
//!   `Some(None)`, value → `Some(Some(v))`), plus typed `chrono` date/time;
//! - **known/unknown discriminators** — the generated union
//!   `Serialize`/`Deserialize` dispatch, including unknown-tag retention for
//!   open unions and rejection for closed ones (G-10/G-11).
//!
//! Generated from the same IR, so the tests track the real types.

use std::fmt::Write as _;

use gantry_ir as ir;
use gantry_ir::naming::snake;
use gantry_sema::Analysis;

use crate::GeneratedFile;
use crate::models::{module_name, type_name, variant_ident};

/// Generate the round-trip test modules: the fixed serialization behavioral
/// tests plus one `#[test]` per discriminated union.
pub fn generate_tests(analysis: &Analysis<'_>) -> Vec<GeneratedFile> {
    let program = analysis.program;

    let mut body = String::from(
        "// Code generated by box-gantry. DO NOT EDIT.\n\n\
         //! Per-union round-trip tests: known-tag dispatch (with discriminator\n\
         //! survival on re-serialize) and open-union unknown retention /\n\
         //! closed-union rejection (VR-4).\n\n",
    );
    for decl in &program.decls {
        let ir::DeclKind::Union(union) = &decl.kind else {
            continue;
        };
        let Some(discriminator) = &union.discriminator else {
            continue;
        };
        // The first variant that carries both a discriminator value and a
        // declared (struct) type — the one the known-tag test targets.
        let Some((value, variant_id)) =
            union
                .variants
                .iter()
                .find_map(|v| match (&v.discriminator_value, &v.ty) {
                    (Some(value), ir::Type::Decl(id)) => Some((value.clone(), *id)),
                    _ => None,
                })
        else {
            continue;
        };

        let module = module_name(&decl.module);
        let union_name = type_name(decl.name.as_str());
        // The enum variant name comes from the discriminator value (matching
        // `models`), not the variant's type name.
        let variant_name = variant_ident(&value);
        let open = matches!(union.extensibility, ir::Extensibility::Open);

        // Can a minimal `{"disc":"value"}` object deserialize into the variant?
        // Only when the variant struct has no required field beyond the
        // discriminator; and the discriminator survives a re-serialize only
        // when the variant actually carries that field.
        let (safe, carries_disc) = match &program.decl(variant_id).kind {
            ir::DeclKind::Struct(s) => {
                let extra_required = s.fields.iter().any(|f| {
                    !matches!(f.ty, ir::Type::Optional(_)) && f.wire_name != *discriminator
                });
                let carries = s.fields.iter().any(|f| f.wire_name == *discriminator);
                (!extra_required, carries)
            }
            ir::DeclKind::Union(_) | ir::DeclKind::Enum(_) | ir::DeclKind::Alias(_) => {
                (false, false)
            }
        };

        let fn_name = format!("{module}_{}_round_trip", snake(decl.name.as_str()));
        let known_doc = json_object(discriminator, &value);
        let unknown_doc = json_object(discriminator, "__gantry_unknown__");
        let value_lit = format!("{value:?}");

        let _ = writeln!(body, "#[test]");
        let _ = writeln!(body, "fn {fn_name}() {{");
        let need_alias = safe || open;
        if need_alias {
            let _ = writeln!(body, "    use crate::models::{module}::{union_name} as U;");
        }
        if safe {
            let _ = writeln!(body, "    let doc = {known_doc};");
            let _ = writeln!(
                body,
                "    let known: U = serde_json::from_str(doc).unwrap();"
            );
            let _ = writeln!(body, "    assert!(matches!(known, U::{variant_name}(_)));");
            if carries_disc {
                let _ = writeln!(
                    body,
                    "    let out = serde_json::to_string(&known).unwrap();"
                );
                let _ = writeln!(body, "    assert!(out.contains({value_lit}));");
            }
        }
        if open {
            let _ = writeln!(body, "    let raw = {unknown_doc};");
            let _ = writeln!(
                body,
                "    let unknown: U = serde_json::from_str(raw).unwrap();"
            );
            let _ = writeln!(body, "    assert!(matches!(unknown, U::Unknown(_)));");
        } else {
            let _ = writeln!(body, "    let raw = {unknown_doc};");
            let _ = writeln!(
                body,
                "    let rejected = serde_json::from_str::<crate::models::{module}::{union_name}>(raw);"
            );
            let _ = writeln!(body, "    assert!(rejected.is_err());");
        }
        let _ = writeln!(body, "}}\n");
    }
    // Exactly one trailing newline (rustfmt-clean).
    body.truncate(body.trim_end().len());
    body.push('\n');

    vec![
        GeneratedFile {
            path: "src/serialization_tests.rs".to_string(),
            content: SERIALIZATION_TEST.to_string(),
        },
        GeneratedFile {
            path: "src/roundtrip_tests.rs".to_string(),
            content: body,
        },
    ]
}

/// A Rust string literal whose value is the JSON object `{"key":"value"}` —
/// built through `{:?}` so both parts are correctly escaped.
fn json_object(key: &str, value: &str) -> String {
    let object = format!("{{{key:?}:{value:?}}}");
    format!("{object:?}")
}

/// Fixed behavioral tests for the serialization layer: the tri-state on read
/// and write (D-110) and typed `chrono` date/time round-trips (VR-4).
const SERIALIZATION_TEST: &str = r####"// Code generated by box-gantry. DO NOT EDIT.

//! Serialization behavioral tests: the write/read tri-state (absent / null /
//! value) and typed date/time round-trips (VR-4).

use crate::serde_helpers::double_option;
use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize)]
struct TriState {
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        deserialize_with = "double_option"
    )]
    field: Option<Option<String>>,
}

#[test]
fn nullable_write_tri_state() {
    // The tri-state is expressed on write (Box clear-on-update): absent omits
    // the key, null serializes null, a value serializes the value.
    let absent = serde_json::to_string(&TriState { field: None }).unwrap();
    assert_eq!(absent, "{}");

    let null = serde_json::to_string(&TriState { field: Some(None) }).unwrap();
    assert_eq!(null, r#"{"field":null}"#);

    let value = serde_json::to_string(&TriState {
        field: Some(Some("x".to_string())),
    })
    .unwrap();
    assert_eq!(value, r#"{"field":"x"}"#);
}

#[test]
fn nullable_read_tri_state() {
    // A present value reads as Some(Some(v)); a present null reads as Some(None)
    // via double_option; an absent field reads as None (serde default).
    let value: TriState = serde_json::from_str(r#"{"field":"y"}"#).unwrap();
    assert_eq!(value.field, Some(Some("y".to_string())));

    let null: TriState = serde_json::from_str(r#"{"field":null}"#).unwrap();
    assert_eq!(null.field, Some(None));

    let absent: TriState = serde_json::from_str("{}").unwrap();
    assert_eq!(absent.field, None);
}

#[test]
fn date_round_trip() {
    // A full-date `NaiveDate` serializes to exactly Box's `2020-01-31` wire form.
    let date: chrono::NaiveDate = serde_json::from_str(r#""2026-07-12""#).unwrap();
    assert_eq!(date.to_string(), "2026-07-12");
    assert_eq!(serde_json::to_string(&date).unwrap(), r#""2026-07-12""#);
}

#[test]
fn date_time_round_trip() {
    // An RFC 3339 `DateTime<Utc>` round-trips through serde without drift.
    let source = r#""2026-07-12T08:30:00Z""#;
    let dt: chrono::DateTime<chrono::Utc> = serde_json::from_str(source).unwrap();
    let encoded = serde_json::to_string(&dt).unwrap();
    let back: chrono::DateTime<chrono::Utc> = serde_json::from_str(&encoded).unwrap();
    assert_eq!(dt, back);
}
"####;
