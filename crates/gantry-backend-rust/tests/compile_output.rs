//! VR-1.2: generate the full real spec's SDK (models + async managers/client +
//! runtime stubs) → `cargo fmt --check` + `cargo check` + `clippy -D warnings`
//! clean. The primary Rust CI signal (TR-Rust.4), the same real-toolchain loop
//! that anchored the Go backend.

use std::path::{Path, PathBuf};
use std::process::Command;

use gantry_spec::SpecSet;
use gantry_verify::scratch::ScratchDir;

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/specs")
        .join(name)
}

fn generate() -> Vec<gantry_backend_rust::GeneratedFile> {
    let set = SpecSet::load(&[
        fixture("openapi.json"),
        fixture("openapi-v2025.0.json"),
        fixture("openapi-v2026.0.json"),
    ])
    .unwrap();
    let build = gantry_backend_rust::BuildInfo::new(set.fingerprint());
    let lowering = gantry_spec::lower(&set).unwrap();
    let program = Box::leak(Box::new(lowering.program));
    let analysis = gantry_sema::analyze(program).unwrap();
    gantry_backend_rust::generate(&analysis, &gantry_manifest::rust(), &build)
}

fn write_all(dir: &Path, files: &[gantry_backend_rust::GeneratedFile]) {
    for file in files {
        let path = dir.join(&file.path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, &file.content).unwrap();
    }
}

#[test]
fn generation_is_deterministic() {
    let once = generate();
    let twice = generate();
    assert_eq!(once.len(), twice.len());
    for (a, b) in once.iter().zip(&twice) {
        assert_eq!(a.path, b.path);
        assert_eq!(a.content, b.content, "nondeterministic: {}", a.path);
    }
    // Every generated Rust file carries the do-not-edit header (FR-6.3).
    for file in &once {
        if file.path.ends_with(".rs") {
            assert!(
                file.content.starts_with("// Code generated by "),
                "{} lacks the header",
                file.path
            );
        }
    }
    // The module tree: one module file per IR module plus the mod root.
    assert!(once.iter().any(|f| f.path == "src/models/mod.rs"));
    assert!(once.iter().any(|f| f.path == "src/models/schemas.rs"));
    // The per-manager schema-file split (D-201): most of the 884 real decls
    // are exclusively owned by one manager and split out of the catch-all,
    // which shrinks accordingly. Pinned loosely (a real ceiling, not an exact
    // count) so ordinary spec growth doesn't trip it — the tight numbers live
    // in gantry-spec's real_specs.rs.
    let schema_buckets: Vec<&str> = once
        .iter()
        .filter_map(|f| f.path.strip_prefix("src/models/schemas/"))
        .filter(|name| name.ends_with(".rs"))
        .collect();
    assert!(
        schema_buckets.len() > 20,
        "expected the schema split to produce more than 20 bucket files, got {}: {schema_buckets:?}",
        schema_buckets.len()
    );
    assert!(
        schema_buckets.contains(&"ai.rs"),
        "expected a src/models/schemas/ai.rs bucket, got {schema_buckets:?}"
    );
    let catch_all = once
        .iter()
        .find(|f| f.path == "src/models/schemas.rs")
        .expect("the schemas catch-all must still be generated");
    let catch_all_lines = catch_all.content.lines().count();
    assert!(
        catch_all_lines < 6_000,
        "src/models/schemas.rs is {catch_all_lines} lines — the per-manager split regressed \
         (was 12,935 before D-201)"
    );
    // The managers/client/runtime layer (M5 slice 3).
    assert!(once.iter().any(|f| f.path == "src/managers/mod.rs"));
    assert!(once.iter().any(|f| f.path == "src/client.rs"));
    // The runtime is vendored as a module tree, not the single-file stub (D-192).
    assert!(once.iter().any(|f| f.path == "src/runtime/mod.rs"));
    assert!(once.iter().any(|f| f.path == "src/internal.rs"));
    // Methods are async and route through the runtime contract, never direct
    // HTTP (FR-5.2).
    let files = once
        .iter()
        .find(|f| f.path == "src/managers/files.rs")
        .unwrap();
    assert!(files.content.contains("pub async fn "), "{}", files.path);
    assert!(files.content.contains("self.session.fetch(req).await?"));
    // Option A (FR-7.3): the public list method *is* the async paginator; the
    // single-page fetch it drives is the private `<method>_page`. No `_paginate`.
    let folders = once
        .iter()
        .find(|f| f.path == "src/managers/folders.rs")
        .unwrap();
    assert!(folders.content.contains("Paginator {"), "{}", folders.path);
    assert!(
        folders.content.contains("pub fn list_items(")
            && folders.content.contains(") -> FoldersListItemsPaginator {"),
        "{}",
        folders.path
    );
    assert!(
        folders.content.contains("async fn list_items_page(")
            && !folders.content.contains("pub async fn list_items_page("),
        "{}",
        folders.path
    );
    assert!(!folders.content.contains("_paginate("), "{}", folders.path);
    assert!(folders.content.contains("pub async fn next(&mut self)"));
    // Reference docs (FR-7.7): an index, one page per manager, and the three
    // cross-cutting guides — describing the real Rust surface.
    assert!(once.iter().any(|f| f.path == "docs/README.md"));
    assert!(
        once.iter()
            .any(|f| f.path.starts_with("docs/managers/") && f.path.ends_with(".md")),
        "expected per-manager doc pages"
    );
    // Every method section carries a synthesized call snippet (FR-7.7): one
    // `**Example**` per `## <method>` heading, each a `rust` fence through the
    // client.
    for page in once
        .iter()
        .filter(|f| f.path.starts_with("docs/managers/") && f.path.ends_with(".md"))
    {
        let methods = page.content.matches("\n## ").count();
        let examples = page.content.matches("**Example**").count();
        assert_eq!(
            methods, examples,
            "{}: {methods} methods but {examples} example snippets",
            page.path
        );
        assert!(
            page.content.contains("```rust\n") && page.content.contains("client."),
            "{} example snippet is missing",
            page.path
        );
    }
    for guide in ["docs/auth.md", "docs/pagination.md", "docs/errors.md"] {
        assert!(once.iter().any(|f| f.path == guide), "missing {guide}");
    }
    // The auth guide documents every Box auth flow, and describes types with
    // the real Rust surface (chrono-typed, `Result`-returning).
    let auth = once.iter().find(|f| f.path == "docs/auth.md").unwrap();
    for flow in ["Developer Token", "Client Credentials", "JWT", "OAuth"] {
        assert!(auth.content.contains(flow), "auth guide missing {flow}");
    }

    // Generated round-trip / behavioral tests (FR-7.8, VR-4): the fixed
    // serialization tests plus one per-union round-trip test, run by the VR-1.2
    // gate's `cargo test`.
    assert!(once.iter().any(|f| f.path == "src/serialization_tests.rs"));
    let roundtrip = once
        .iter()
        .find(|f| f.path == "src/roundtrip_tests.rs")
        .unwrap();
    assert!(
        roundtrip.content.contains("_round_trip("),
        "expected generated per-union round-trip tests"
    );

    // The client wires one manager field per API area over a shared session.
    let client = once.iter().find(|f| f.path == "src/client.rs").unwrap();
    assert!(client.content.contains("pub struct Client {"));
    assert!(
        client
            .content
            .contains("Self::from_session(crate::runtime::Client::new(auth))")
    );
    assert!(
        client
            .content
            .contains("let session = std::sync::Arc::new(session);")
    );
    // Date/time fields are typed via chrono (not strings), and the crate
    // manifest declares the lean chrono dependency.
    let models: String = once
        .iter()
        .filter(|f| f.path.starts_with("src/models/"))
        .map(|f| f.content.as_str())
        .collect();
    assert!(
        models.contains("chrono::NaiveDate"),
        "date fields should be chrono-typed"
    );
    assert!(
        models.contains("chrono::DateTime<chrono::Utc>"),
        "date-time fields should be chrono-typed"
    );
    // Model structs derive `Default` (D-196), so a body can be built with
    // `Type { field: x, ..Default::default() }` instead of naming every field.
    // The compile gate proves the derive is satisfiable fleet-wide; this pins
    // that it's emitted (open enums/unions carry it so structs can).
    assert!(
        models.contains(
            "#[derive(Clone, Debug, Default, PartialEq, serde::Deserialize, serde::Serialize)]"
        ),
        "model structs should derive Default (D-196)"
    );
    let cargo = once.iter().find(|f| f.path == "Cargo.toml").unwrap();
    assert!(cargo.content.contains(
        "chrono = { version = \"0.4\", default-features = false, features = [\"serde\", \"alloc\"] }"
    ));
    // NF-8: publish-ready manifest metadata + a shipped README.
    for meta in ["description = ", "license = ", "repository = ", "readme = "] {
        assert!(cargo.content.contains(meta), "Cargo.toml missing {meta}");
    }
    assert!(once.iter().any(|f| f.path == "README.md"));
}

