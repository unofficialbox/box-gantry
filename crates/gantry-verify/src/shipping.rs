//! Ship-readiness: a generated tree must be *functional*, not merely buildable.
//!
//! `gantry-contract` renders a compile-only stub of the runtime surface so a
//! generated SDK type-checks without the hand-written runtime (FR-5.3). That
//! stub is a verification device: every method body raises. Shipping it produces
//! an SDK that compiles, passes `vet`/`clippy`/`tsc`, packages cleanly, and then
//! fails on the first real call.
//!
//! That is exactly what happened to `box-open-go-sdk@v0.1.0` (D-192): every
//! compile gate was green because compiling was all they checked. This module
//! adds the check none of them made — that no shipped artifact still carries the
//! stub — so the failure mode cannot recur silently.

/// Markers the contract's stub renderers emit into every unimplemented body.
///
/// Deliberately taken from the *stub text*, not from language keywords: a
/// `panic!`/`throw` in hand-written runtime code is legitimate, whereas these
/// strings appear only in generated stubs.
const STUB_MARKERS: &[&str] = &[
    "gantryruntime stub:",
    "not wired to a real runtime",
    "Compilable stubs for the hand-written runtime surface",
];

/// A shipped file still carrying runtime-stub markers.
#[derive(Debug, PartialEq, Eq)]
pub struct StubFinding {
    /// Path of the offending file, relative to the SDK root.
    pub path: String,
    /// The marker that matched.
    pub marker: &'static str,
}

/// Find shipped files that still carry the compile-only runtime stub.
///
/// Returns every match rather than the first: a partial vendoring (one language
/// updated, another missed) should surface as a complete list, not one file at a
/// time across repeated runs.
pub fn stub_findings<'a>(files: impl IntoIterator<Item = (&'a str, &'a str)>) -> Vec<StubFinding> {
    let mut findings = Vec::new();
    for (path, content) in files {
        for marker in STUB_MARKERS {
            if content.contains(marker) {
                findings.push(StubFinding {
                    path: path.to_string(),
                    marker,
                });
                break;
            }
        }
    }
    findings
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_vendored_runtime_is_clean() {
        let files = [
            ("gantryruntime/runtime.go", "func Do() { client.Do(req) }"),
            ("managers/files.go", "// Code generated by box-gantry"),
        ];
        assert_eq!(stub_findings(files), []);
    }

    #[test]
    fn a_shipped_stub_is_reported_with_its_path() {
        let files = [(
            "src/runtime.rs",
            "unimplemented!(\"gantryruntime stub: Stream::empty is not wired to a real runtime\")",
        )];
        let findings = stub_findings(files);
        assert_eq!(findings.len(), 1);
        assert_eq!(findings[0].path, "src/runtime.rs");
    }

    /// Every stub-bearing file is reported, so a partial vendoring surfaces at
    /// once instead of one file per run.
    #[test]
    fn every_offending_file_is_reported() {
        let files = [
            (
                "src/runtime.ts",
                "throw new Error('not wired to a real runtime')",
            ),
            ("ok.ts", "export const x = 1;"),
            (
                "Runtime.java",
                "// Compilable stubs for the hand-written runtime surface",
            ),
        ];
        let findings = stub_findings(files);
        assert_eq!(findings.len(), 2);
        assert_eq!(findings[0].path, "src/runtime.ts");
        assert_eq!(findings[1].path, "Runtime.java");
    }
}
