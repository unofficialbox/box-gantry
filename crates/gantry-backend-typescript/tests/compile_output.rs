//! VR-1.5: generate the full real spec's TypeScript model layer → `tsc
//! --noEmit` clean under `strict`. The primary TypeScript CI signal, the same
//! real-toolchain loop that anchors the Go/Rust backends.

use std::path::{Path, PathBuf};
use std::process::Command;

use gantry_spec::SpecSet;

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/specs")
        .join(name)
}

fn generate() -> Vec<gantry_backend_typescript::GeneratedFile> {
    let set = SpecSet::load(&[
        fixture("openapi.json"),
        fixture("openapi-v2025.0.json"),
        fixture("openapi-v2026.0.json"),
    ])
    .unwrap();
    let build = gantry_backend_typescript::BuildInfo::new(set.fingerprint());
    let lowering = gantry_spec::lower(&set).unwrap();
    let program = Box::leak(Box::new(lowering.program));
    let analysis = gantry_sema::analyze(program).unwrap();
    gantry_backend_typescript::generate(&analysis, &gantry_manifest::typescript(), &build)
}

fn write_all(dir: &Path, files: &[gantry_backend_typescript::GeneratedFile]) {
    for file in files {
        let path = dir.join(&file.path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, &file.content).unwrap();
    }
}

#[test]
fn generation_is_deterministic() {
    let once = generate();
    let twice = generate();
    assert_eq!(once.len(), twice.len());
    for (a, b) in once.iter().zip(&twice) {
        assert_eq!(a.path, b.path);
        assert_eq!(a.content, b.content, "nondeterministic: {}", a.path);
    }
    // Every generated `.ts` file carries the do-not-edit header (FR-6.3).
    for file in &once {
        if file.path.ends_with(".ts") {
            assert!(
                file.content.starts_with("// Code generated by "),
                "{} lacks the header",
                file.path
            );
        }
    }
    // The package scaffold + module tree.
    assert!(once.iter().any(|f| f.path == "package.json"));
    assert!(once.iter().any(|f| f.path == "tsconfig.json"));
    assert!(once.iter().any(|f| f.path == "src/index.ts"));
    assert!(once.iter().any(|f| f.path == "src/models/index.ts"));

    let models: String = once
        .iter()
        .filter(|f| f.path.starts_with("src/models/") && f.path.ends_with(".ts"))
        .map(|f| f.content.as_str())
        .collect();
    // Structs → interfaces, with the tri-state as `field?: T` (TR-TS.2).
    assert!(
        models.contains("export interface "),
        "no interfaces emitted"
    );
    assert!(models.contains("?: "), "no optional (tri-state) fields");
    // `oneOf` → discriminated unions with an open catch-all (TR-TS.1).
    assert!(
        models.contains(" | { [key: string]: unknown }"),
        "no open-union catch-all member"
    );
    // Open enums → string-literal unions widened with `(string & {})` (TR-TS.1).
    assert!(
        models.contains(" | (string & {})"),
        "no widened open-enum union"
    );
    // Provenance (NF-7).
    let build = once.iter().find(|f| f.path == "src/buildinfo.ts").unwrap();
    assert!(build.content.contains("export const ENGINE ="));
    assert!(build.content.contains("export const SPEC_FINGERPRINT ="));
}

/// VR-1.5: the generated package type-checks clean under `strict` with the
/// TypeScript 7 native compiler (`tsc --noEmit`). CI runs this gate.
#[test]
fn the_real_spec_models_type_check() {
    if Command::new("tsc").arg("--version").output().is_err() {
        eprintln!("SKIPPED: tsc not available; CI runs this gate");
        return;
    }
    let dir = std::env::temp_dir().join(format!("gantry-ts-models-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    write_all(&dir, &generate());

    let check = Command::new("tsc")
        .args(["--noEmit", "-p", "tsconfig.json"])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        check.status.success(),
        "tsc --noEmit failed under strict (VR-1.5):\n{}\n{}",
        String::from_utf8_lossy(&check.stdout),
        String::from_utf8_lossy(&check.stderr)
    );
}
