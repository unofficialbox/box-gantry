//! Reference documentation generation (FR-7.7).
//!
//! Per-manager Markdown plus the auth / pagination / errors cross-cutting
//! guides, generated from the same IR the code is (so the docs describe
//! the real Go surface — method names, types, paged variants — and can't
//! drift from it). Deterministic, like all output (FR-6.2).

use std::collections::HashMap;
use std::fmt::Write as _;

use gantry_ir as ir;
use gantry_ir::naming::pascal;
use gantry_sema::Analysis;
use gantry_synth::PagedOperation;

use crate::managers::method_name;
use crate::models::GeneratedFile;

/// Generate `docs/` — an index, one page per manager, and the guides.
pub fn generate_docs(analysis: &Analysis<'_>, paged: &[PagedOperation]) -> Vec<GeneratedFile> {
    let program = analysis.program;
    let paged_by_op: HashMap<usize, &PagedOperation> =
        paged.iter().map(|p| (p.operation, p)).collect();

    let mut files = Vec::new();
    files.push(index_page(analysis));
    let zips = gantry_synth::detect_zip_downloads(analysis);
    for (manager, op_indices) in &analysis.managers {
        let mut page = manager_page(program, &paged_by_op, manager, op_indices);
        if zips.iter().any(|z| op_indices.contains(&z.create)) {
            page.content.push_str(ZIP_DOWNLOAD_SECTION);
        }
        files.push(page);
    }
    files.push(guide("auth", AUTH_GUIDE));
    files.push(guide("pagination", PAGINATION_GUIDE));
    files.push(guide("errors", ERRORS_GUIDE));
    files.push(guide("webhooks", WEBHOOKS_GUIDE));
    files
}

fn index_page(analysis: &Analysis<'_>) -> GeneratedFile {
    let mut body = String::from(
        "<!-- Generated by box-gantry. DO NOT EDIT. -->\n# Box SDK reference\n\n\
         One resource manager per Box API tag, reached through the single\n\
         `client.Client` entry point.\n\n## Guides\n\n\
         - [Authentication](auth.md)\n- [Pagination](pagination.md)\n- [Errors](errors.md)\n- [Webhooks](webhooks.md)\n\n\
         ## Managers\n\n| Manager | Operations |\n|---|---|\n",
    );
    for (manager, ops) in &analysis.managers {
        let _ = writeln!(
            body,
            "| [{name}](managers/{manager}.md) | {count} |",
            name = pascal(manager),
            count = ops.len(),
        );
    }
    GeneratedFile {
        path: "docs/README.md".to_string(),
        content: body,
    }
}

fn manager_page(
    program: &ir::Program,
    paged: &HashMap<usize, &PagedOperation>,
    manager: &str,
    op_indices: &[usize],
) -> GeneratedFile {
    let mut body = format!(
        "<!-- Generated by box-gantry. DO NOT EDIT. -->\n# {}Manager\n\n\
         Access via `client.NewClient().{}`.\n\n",
        pascal(manager),
        pascal(manager),
    );
    for &index in op_indices {
        let op = &program.operations[index];
        let method = method_name(op);
        let _ = writeln!(body, "## {method}\n");
        if op.deprecated {
            body.push_str("> **Deprecated.**\n\n");
        }
        let _ = writeln!(
            body,
            "`{http} {path}`\n",
            http = http_method(op.method),
            path = render_path(op),
        );

        let params: Vec<&ir::Param> = op.params.iter().collect();
        if !params.is_empty() {
            body.push_str("| Parameter | In | Type | Required |\n|---|---|---|---|\n");
            for param in &params {
                let required = !matches!(param.ty, ir::Type::Optional(_));
                let _ = writeln!(
                    body,
                    "| `{name}` | {loc} | `{ty}` | {req} |",
                    name = param.wire_name,
                    loc = param_location(param.location),
                    ty = describe(program, unwrap(&param.ty)),
                    req = if required { "yes" } else { "no" },
                );
            }
            body.push('\n');
        }
        if let Some(req) = &op.request {
            let _ = writeln!(
                body,
                "**Request body** (`{media}`): `{ty}`\n",
                media = request_media(req.media),
                ty = describe(program, unwrap(&req.ty)),
            );
        }
        let _ = writeln!(
            body,
            "**Returns:** {}\n",
            describe_response(program, &op.response)
        );
        let _ = writeln!(
            body,
            "**Example**\n\n{}",
            call_snippet(program, manager, op, &method, paged.contains_key(&index))
        );
        if paged.contains_key(&index) {
            let _ = writeln!(
                body,
                "Paginated — `{method}(...)` returns `iter.Seq2[*T, error]`, \
                 threading the cursor for you. See the [pagination guide](../pagination.md).\n"
            );
        }
    }
    GeneratedFile {
        path: format!("docs/managers/{manager}.md"),
        content: body,
    }
}

fn guide(name: &str, content: &str) -> GeneratedFile {
    GeneratedFile {
        path: format!("docs/{name}.md"),
        content: format!("<!-- Generated by box-gantry. DO NOT EDIT. -->\n{content}"),
    }
}

/// A call snippet for one operation: the manager method with placeholder
/// arguments in the printer's order (`ctx`, required params, body, then a `nil`
/// options struct) and idiomatic result/error handling. A shape-correct
/// fragment — argument count and order match the real signature; the values are
/// placeholders — so the docs show *how to call* every method, not just its
/// shape (FR-7.7).
fn call_snippet(
    program: &ir::Program,
    manager: &str,
    op: &ir::Operation,
    method: &str,
    paged: bool,
) -> String {
    let mut args = vec!["context.Background()".to_string()];
    let mut has_optional = false;
    for param in &op.params {
        if matches!(param.ty, ir::Type::Optional(_)) {
            has_optional = true;
        } else {
            args.push(go_placeholder(program, &param.ty, &param.wire_name));
        }
    }
    if let Some(req) = &op.request {
        args.push(go_body_literal(program, unwrap(&req.ty)));
    }
    if has_optional {
        args.push("nil".to_string());
    }
    let call = format!("client.{}.{method}({})", pascal(manager), args.join(", "));

    let mut out = String::from("```go\n");
    if paged {
        let _ = writeln!(
            out,
            "for item, err := range {call} {{\n\
             \tif err != nil {{\n\t\tlog.Fatal(err)\n\t}}\n\tfmt.Println(item)\n}}"
        );
    } else if matches!(op.response, ir::ResponseShape::None) {
        let _ = writeln!(out, "if err := {call}; err != nil {{\n\tlog.Fatal(err)\n}}");
    } else {
        let _ = writeln!(
            out,
            "result, err := {call}\n\
             if err != nil {{\n\tlog.Fatal(err)\n}}\nfmt.Println(result)"
        );
    }
    out.push_str("```\n");
    out
}

/// A placeholder value for a required argument, by type. Strings show the
/// parameter name (upper-cased) so the call reads intelligibly.
fn go_placeholder(program: &ir::Program, ty: &ir::Type, wire_name: &str) -> String {
    match unwrap(ty) {
        ir::Type::String => format!("\"{}\"", wire_name.to_uppercase()),
        ir::Type::Int64 | ir::Type::Float64 => "0".to_string(),
        ir::Type::Bool => "false".to_string(),
        ir::Type::Date => "serialization.Date{}".to_string(),
        ir::Type::DateTime => "time.Time{}".to_string(),
        // Go lowers an enum to `type Name string` (models.rs), so its zero value
        // is a string conversion, not a composite literal; a struct/union is the
        // composite literal; an alias defers to what it aliases.
        ir::Type::Decl(id) => {
            let decl = program.decl(*id);
            match &decl.kind {
                ir::DeclKind::Enum(_) => format!("schemas.{}(\"...\")", decl.name.as_str()),
                ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => {
                    format!("schemas.{}{{}}", decl.name.as_str())
                }
                ir::DeclKind::Alias(inner) => go_placeholder(program, inner, wire_name),
            }
        }
        // Lists, maps, JSON, and binary rarely appear as required scalars; a
        // nil is the honest placeholder for the call shape.
        ir::Type::List(_)
        | ir::Type::Map(_)
        | ir::Type::JsonValue
        | ir::Type::Binary
        | ir::Type::Optional(_)
        | ir::Type::Nullable(_) => "nil".to_string(),
    }
}

/// A placeholder literal for a request body: a struct/union-decl body is an
/// empty composite literal by pointer; an enum body is a string conversion; a
/// map/list body is its own literal.
fn go_body_literal(program: &ir::Program, ty: &ir::Type) -> String {
    match ty {
        ir::Type::Decl(id) => {
            let decl = program.decl(*id);
            match &decl.kind {
                ir::DeclKind::Enum(_) => format!("schemas.{}(\"...\")", decl.name.as_str()),
                ir::DeclKind::Alias(inner) => go_body_literal(program, inner),
                ir::DeclKind::Struct(_) | ir::DeclKind::Union(_) => {
                    format!("&schemas.{}{{}}", decl.name.as_str())
                }
            }
        }
        ir::Type::Map(v) => format!("map[string]{}{{}}", describe(program, v)),
        ir::Type::List(v) => format!("[]{}{{}}", describe(program, v)),
        ir::Type::Bool
        | ir::Type::Int64
        | ir::Type::Float64
        | ir::Type::String
        | ir::Type::Date
        | ir::Type::DateTime
        | ir::Type::Binary
        | ir::Type::JsonValue
        | ir::Type::Optional(_)
        | ir::Type::Nullable(_) => "nil".to_string(),
    }
}

/// A readable (Go-flavored) name for a type, for docs only.
fn describe(program: &ir::Program, ty: &ir::Type) -> String {
    match ty {
        ir::Type::Bool => "bool".into(),
        ir::Type::Int64 => "int64".into(),
        ir::Type::Float64 => "float64".into(),
        ir::Type::String => "string".into(),
        ir::Type::Date => "Date".into(),
        ir::Type::DateTime => "time.Time".into(),
        ir::Type::Binary => "io.Reader".into(),
        ir::Type::JsonValue => "any".into(),
        ir::Type::List(inner) => format!("[]{}", describe(program, inner)),
        ir::Type::Map(inner) => format!("map[string]{}", describe(program, inner)),
        ir::Type::Decl(id) => program.decl(*id).name.as_str().to_string(),
        ir::Type::Optional(inner) => format!("Optional<{}>", describe(program, inner)),
        ir::Type::Nullable(inner) => format!("Nullable<{}>", describe(program, inner)),
    }
}

fn describe_response(program: &ir::Program, response: &ir::ResponseShape) -> String {
    match response {
        ir::ResponseShape::None => "no content".into(),
        ir::ResponseShape::Json(ty) => format!("`{}`", describe(program, unwrap(ty))),
        ir::ResponseShape::Binary => "a binary stream (`io.Reader`)".into(),
        ir::ResponseShape::Text => "text (`string`)".into(),
        ir::ResponseShape::Redirect => "a redirect URL (`string`)".into(),
    }
}

fn unwrap(ty: &ir::Type) -> &ir::Type {
    match ty {
        ir::Type::Optional(inner) | ir::Type::Nullable(inner) => unwrap(inner),
        ir::Type::Bool
        | ir::Type::Int64
        | ir::Type::Float64
        | ir::Type::String
        | ir::Type::Date
        | ir::Type::DateTime
        | ir::Type::Binary
        | ir::Type::JsonValue
        | ir::Type::List(_)
        | ir::Type::Map(_)
        | ir::Type::Decl(_) => ty,
    }
}

fn render_path(op: &ir::Operation) -> String {
    let mut out = String::new();
    for segment in &op.path {
        out.push('/');
        match segment {
            ir::PathSegment::Literal(text) => out.push_str(text),
            ir::PathSegment::Parameter(name) => {
                let _ = write!(out, "{{{}}}", name.as_str());
            }
            ir::PathSegment::Composite(parts) => {
                for part in parts {
                    match part {
                        ir::PathPart::Literal(text) => out.push_str(text),
                        ir::PathPart::Parameter(name) => {
                            let _ = write!(out, "{{{}}}", name.as_str());
                        }
                    }
                }
            }
        }
    }
    out
}

fn http_method(method: ir::HttpMethod) -> &'static str {
    match method {
        ir::HttpMethod::Get => "GET",
        ir::HttpMethod::Put => "PUT",
        ir::HttpMethod::Post => "POST",
        ir::HttpMethod::Delete => "DELETE",
        ir::HttpMethod::Options => "OPTIONS",
        ir::HttpMethod::Head => "HEAD",
        ir::HttpMethod::Patch => "PATCH",
        ir::HttpMethod::Trace => "TRACE",
    }
}

fn param_location(location: ir::ParamLocation) -> &'static str {
    match location {
        ir::ParamLocation::Path => "path",
        ir::ParamLocation::Query => "query",
        ir::ParamLocation::Header => "header",
    }
}

fn request_media(media: ir::RequestMedia) -> &'static str {
    match media {
        ir::RequestMedia::Json => "application/json",
        ir::RequestMedia::JsonPatch => "application/json-patch+json",
        ir::RequestMedia::UrlEncoded => "application/x-www-form-urlencoded",
        ir::RequestMedia::Multipart => "multipart/form-data",
        ir::RequestMedia::OctetStream => "application/octet-stream",
    }
}

const AUTH_GUIDE: &str = "# Authentication\n\n\
Every request is authorized through the runtime's token source: the\n\
generated code calls `AccessToken(ctx)` and attaches the bearer token,\n\
and the network layer refreshes on a `401` and retries once. Pass one of\n\
the four Box auth flows — from the `auth` package — to `client.NewClient`\n\
at construction; each is a `gantryruntime.TokenSource` that caches its\n\
access token until shortly before it expires.\n\n\
## Developer Token\n\n\
```go\n\
c := client.NewClient(auth.DeveloperToken(\"DEVELOPER_TOKEN\"))\n\
```\n\n\
## Client Credentials Grant (server auth, no key)\n\n\
```go\n\
c := client.NewClient(auth.ClientCredentials(auth.CCGConfig{\n\
\tClientID:     \"CLIENT_ID\",\n\
\tClientSecret: \"CLIENT_SECRET\",\n\
\tEnterpriseID: \"ENTERPRISE_ID\", // or set UserID to act as a managed user\n\
}))\n\
```\n\n\
## JWT (server auth with a signing key)\n\n\
```go\n\
src, err := auth.JWTAuth(auth.JWTConfig{\n\
\tClientID:      \"CLIENT_ID\",\n\
\tClientSecret:  \"CLIENT_SECRET\",\n\
\tPublicKeyID:   \"PUBLIC_KEY_ID\",\n\
\tPrivateKeyPEM: privateKeyPEM, // optionally encrypted; set Passphrase\n\
\tEnterpriseID:  \"ENTERPRISE_ID\",\n\
})\n\
if err != nil {\n\t// bad key: fails loudly at construction\n}\n\
c := client.NewClient(src)\n\
```\n\n\
## OAuth 2.0 (authorization code)\n\n\
Redirect the user to `cfg.AuthorizeURL(redirectURI, state)` and exchange the\n\
returned code. Box rotates the refresh token on every refresh and rejects the\n\
old one, so give the config a `Store` (any type with\n\
`SaveRefreshToken(ctx, token) error`) that writes it somewhere durable; it is\n\
called with the token the exchange issues and with every rotation after. Later\n\
runs resume from the newest saved token:\n\n\
```go\n\
cfg := auth.OAuthConfig{ClientID: \"CLIENT_ID\", ClientSecret: \"CLIENT_SECRET\", Store: tokenStore}\n\
src, err := cfg.ExchangeCode(ctx, code, redirectURI)\n\
// later runs: src := auth.OAuth(cfg, newestSavedRefreshToken)\n\
c := client.NewClient(src)\n\
```\n\n\
## Acting as another user\n\n\
An admin, or a service account whose app may *make API calls using the as-user\n\
header*, can act as another user. `WithAsUserHeader` returns a new client whose\n\
every call sends Box's `As-User` header; it shares the original's auth and\n\
configuration, and the original is unchanged:\n\n\
```go\n\
userClient := c.WithAsUserHeader(\"USER_ID\")\n\
me, err := userClient.Users.GetMe(ctx, nil) // the user USER_ID\n\
```\n\n\
## Downscoping a token\n\n\
Exchange the session's access token for one limited to `scopes` and,\n\
optionally, to one item (its API URL) or shared link — e.g. to hand a\n\
browser-side preview a narrow token. The result has no refresh token; build\n\
a client from it with `auth.DeveloperToken`:\n\n\
```go\n\
down, err := c.Authorization.DownscopeToken(ctx, []string{\"item_preview\"},\n\
\t\"https://api.box.com/2.0/files/123\", \"\")\n\
if err != nil {\n\
\treturn err\n\
}\n\
preview := client.NewClient(auth.DeveloperToken(*down.AccessToken))\n\
```\n";

const PAGINATION_GUIDE: &str = "# Pagination\n\n\
Marker- and offset-paginated list operations return an\n\
`iter.Seq2[*T, error]` — the list method *is* the paginator. Range over it\n\
to walk every page transparently:\n\n\
```go\n\
for item, err := range client.Folders.ListItems(ctx, folderID, nil) {\n\
\tif err != nil {\n\t\treturn err\n\t}\n\t// use item\n}\n\
```\n\n\
The iterator threads the cursor for you and stops when the last page is\n\
reached. It copies the options you pass, so your struct is never\n\
mutated.\n\n\
## Events\n\n\
`client.Events.Stream` follows Box's long-poll event stream: it yields the\n\
events after `opts.StreamPosition` (`\"now\"` when unset), each once — Box may\n\
deliver an event twice — then waits on a real-time server until Box reports a\n\
change. It lists a fresh server when Box asks it to reconnect, and retries a\n\
long poll that times out. It ends when `ctx` does, or when a call fails, with\n\
that error:\n\n\
```go\n\
for event, err := range client.Events.Stream(ctx, nil) {\n\
\tif err != nil {\n\t\treturn err\n\t}\n\t// use event; break to stop\n}\n\
```\n\n\
## Representations (PDF, text, thumbnails)\n\n\
`client.Files.GetRepresentationContent` downloads a rendering of a file that Box\n\
generates on demand — a PDF, its extracted text, page images. `repHints` names it\n\
as Box's `X-Rep-Hints` header does; `assetPath` picks one asset of a multi-asset\n\
representation (`\"1.png\"` for a page) and is `\"\"` for a single-file one. It\n\
waits while Box generates the representation, up to `ctx`'s deadline or\n\
`gantryruntime.DefaultRepresentationWait`, and returns an error if Box fails to:\n\n\
```go\n\
text, err := client.Files.GetRepresentationContent(ctx, fileID, \"[extracted_text]\", \"\")\n\
if err != nil {\n\treturn err\n}\n\
body, err := io.ReadAll(text)\n\
```\n";

const ERRORS_GUIDE: &str = "# Errors\n\
\n\
Every I/O method returns `(T, error)` (Go's idiomatic error model). A\n\
non-nil error is either a transport failure or a non-2xx response after\n\
the network layer's retries (exponential backoff + jitter, `401`\n\
refresh, `Retry-After`). A non-2xx response is a\n\
`*gantryruntime.APIError` carrying the HTTP `Status`, Box's error `Code`,\n\
`Message`, and `RequestID`, the response `Header`, and the raw `Body`:\n\
\n\
```go\n\
var apiErr *gantryruntime.APIError\n\
if errors.As(err, &apiErr) && apiErr.Status == http.StatusNotFound {\n\
\t// apiErr.Code == \"not_found\"; quote apiErr.RequestID to Box support\n\
}\n\
```\n\
\n\
## Etags: `If-None-Match` and `If-Match`\n\
\n\
Files and folders carry an `etag`. Send it back to stay in sync with Box\n\
(Box's [Ensure consistency](https://developer.box.com/guides/api-calls/ensure-consistency/)\n\
guide):\n\
\n\
- **Reads** — a file, folder, or web link `get`, and each shared-item lookup, has an\n\
\x20\x20`…IfModified` variant that takes the stored etag, sends it as\n\
\x20\x20`If-None-Match`, and returns `nil, nil` when Box answers `304 Not Modified`:\n\
\x20\x20keep your cached copy. (The plain method surfaces that 304 as the error\n\
\x20\x20above if you set `if-none-match` on it yourself.)\n\
- **Writes** — pass the etag as `IfMatch` on a file, folder, or web link update or\n\
\x20\x20delete, or a new file version upload. Box answers `412 Precondition\n\
\x20\x20Failed` (code `precondition_failed`) when the item changed since you read\n\
\x20\x20it, and `gantryruntime.IsPreconditionFailed(err)` reports it: read it\n\
\x20\x20again, reapply your change, retry. `If-Match` can't block a move.\n\
\n\
```go\n\
file, err := client.Files.GetIfModified(ctx, fileID, etag, nil)\n\
if err == nil && file == nil {\n\
\t// unchanged since etag\n\
}\n\
\n\
// Re-read and retry: the update lands only on the version it was made from.\n\
for attempt := 1; ; attempt++ {\n\
\t_, err = client.Files.Update(ctx, fileID, body, &managers.FilesUpdateOptions{IfMatch: &etag})\n\
\tif !gantryruntime.IsPreconditionFailed(err) || attempt == 3 {\n\
\t\tbreak\n\
\t}\n\
\tcurrent, err := client.Files.Get(ctx, fileID, nil)\n\
\tif err != nil {\n\
\t\treturn err\n\
\t}\n\
\tetag = current.Etag.Value // reapply your change to current here\n\
}\n\
```\n";

/// Webhooks guide: verifying Box's signature on a webhook delivery with the
/// runtime's verifier.
const WEBHOOKS_GUIDE: &str = "# Webhooks\n\
\n\
Once you generate signature keys for your app (Developer Console → **Webhooks**\n\
→ **Manage signature keys**), Box signs every webhook delivery. Each\n\
`BOX-SIGNATURE-PRIMARY` / `BOX-SIGNATURE-SECONDARY` header is the base64\n\
HMAC-SHA256, under that key, of the request body followed by the\n\
`BOX-DELIVERY-TIMESTAMP` header (Box's\n\
[Verify webhook signatures](https://developer.box.com/guides/webhooks/v2/signatures-v2/)\n\
guide). `gantryruntime.WebhookVerifier` checks a delivery before you trust it:\n\
\n\
```go\n\
verifier := gantryruntime.WebhookVerifier{PrimaryKey: primaryKey, SecondaryKey: secondaryKey}\n\
http.HandleFunc(\"/box/webhook\", func(w http.ResponseWriter, r *http.Request) {\n\
\tbody, err := io.ReadAll(r.Body)\n\
\tif err != nil || !verifier.Verify(body, r.Header) {\n\
\t\thttp.Error(w, \"invalid signature\", http.StatusForbidden)\n\
\t\treturn\n\
\t}\n\
\t// body is a genuine, recent Box event\n\
})\n\
```\n\
\n\
- **Pass the body exactly as received.** Parsed and re-serialized JSON won't\n\
\x20\x20verify.\n\
- **Either key may be missing.** A delivery is genuine when the signature of\n\
\x20\x20any configured key matches, so you can rotate one key while the other keeps\n\
\x20\x20verifying.\n\
- **Old or future deliveries are refused.** A delivery stamped more than ten\n\
\x20\x20minutes ago (`MaxAge`) or in the future fails, which blocks replays.\n\
- **Header names match in any case**, and the comparison takes the same time\n\
\x20\x20wherever a signature differs.\n";

