//! VR-1.1: generate the full real spec's models → `go build` + `go vet`
//! clean, gofmt-clean — the primary CI signal, from the backend's first
//! week (G-1: this loop found 11 bugs snapshot tests never could).

use std::path::{Path, PathBuf};
use std::process::Command;

use gantry_spec::SpecSet;

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/specs")
        .join(name)
}

fn generate() -> Vec<gantry_backend_go::GeneratedFile> {
    let set = SpecSet::load(&[
        fixture("openapi.json"),
        fixture("openapi-v2025.0.json"),
        fixture("openapi-v2026.0.json"),
    ])
    .unwrap();
    let build = gantry_backend_go::BuildInfo::new(set.fingerprint());
    let lowering = gantry_spec::lower(&set).unwrap();
    let program = Box::leak(Box::new(lowering.program));
    let analysis = gantry_sema::analyze(program).unwrap();
    gantry_backend_go::generate(&analysis, &build)
        .expect("the go backend must express the verified program")
}

fn write_all(dir: &Path, files: &[gantry_backend_go::GeneratedFile]) {
    for file in files {
        let path = dir.join(&file.path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, &file.content).unwrap();
    }
}

#[test]
fn generation_is_deterministic() {
    let once = generate();
    let twice = generate();
    assert_eq!(once.len(), twice.len());
    for (a, b) in once.iter().zip(&twice) {
        assert_eq!(a.path, b.path);
        assert_eq!(a.content, b.content, "nondeterministic: {}", a.path);
    }
    // Every generated file carries the do-not-edit header (FR-6.3).
    for file in &once {
        if file.path.ends_with(".go") {
            assert!(
                file.content.starts_with("// Code generated by "),
                "{} lacks the header",
                file.path
            );
        }
    }
    // Pagination iterators are synthesized for the paged operations
    // (FR-7.3, TR-Go.4): 54 marker + 10 offset. Pinned so the count only
    // moves deliberately with the spec (VR-6 lineage). Option A: the exported
    // list method *is* the iterator (returns `iter.Seq2[*T, error]`), so count
    // that return type rather than a `Paginate` suffix.
    let paginators: usize = once
        .iter()
        .filter(|f| f.path.starts_with("managers/"))
        .map(|f| f.content.matches(") iter.Seq2[*").count())
        .sum();
    assert_eq!(paginators, 64, "expected 64 pagination iterators");
    let offset_iters: usize = once
        .iter()
        .filter(|f| f.path.starts_with("managers/"))
        .map(|f| f.content.matches("var offset int64").count())
        .sum();
    assert_eq!(offset_iters, 10, "expected 10 offset iterators");
    // Generated round-trip tests exist (FR-7.8, VR-4): the serialization
    // package test plus per-module union tests.
    assert!(
        once.iter()
            .any(|f| f.path == "serialization/serialization_test.go"),
        "missing generated serialization test"
    );
    let union_tests = once
        .iter()
        .filter(|f| f.path.ends_with("roundtrip_test.go"))
        .count();
    assert!(
        union_tests >= 1,
        "expected generated union round-trip tests"
    );
}

#[test]
fn every_manager_has_reference_docs() {
    let files = generate();
    // Each manager .go file has a matching docs page (FR-7.7).
    let manager_files: Vec<&str> = files
        .iter()
        .filter_map(|f| {
            f.path
                .strip_prefix("managers/")
                .and_then(|p| p.strip_suffix(".go"))
        })
        .filter(|name| *name != "helpers")
        .collect();
    assert!(!manager_files.is_empty());
    for manager in &manager_files {
        let doc_path = format!("docs/managers/{manager}.md");
        let doc = files
            .iter()
            .find(|f| f.path == doc_path)
            .unwrap_or_else(|| panic!("no docs page for manager {manager}"));
        assert!(
            doc.content.contains("Access via `client.NewClient()."),
            "{doc_path} is malformed"
        );
        // Every method section carries a synthesized call snippet (FR-7.7): one
        // `**Example**` per `## <method>` heading, each a runnable-shape `go`
        // fence that calls through the client.
        let methods = doc.content.matches("\n## ").count();
        let examples = doc.content.matches("**Example**").count();
        assert_eq!(
            methods, examples,
            "{doc_path}: {methods} methods but {examples} example snippets"
        );
        assert!(
            doc.content.contains("```go\n") && doc.content.contains("client."),
            "{doc_path} example snippet is missing"
        );
    }
    // The index and the three cross-cutting guides exist (FR-7.7).
    for required in [
        "docs/README.md",
        "docs/auth.md",
        "docs/pagination.md",
        "docs/errors.md",
    ] {
        assert!(
            files.iter().any(|f| f.path == required),
            "missing {required}"
        );
    }
    // The index links every manager page.
    let index = files.iter().find(|f| f.path == "docs/README.md").unwrap();
    for manager in &manager_files {
        assert!(
            index.content.contains(&format!("(managers/{manager}.md)")),
            "index does not link {manager}"
        );
    }
}

#[test]
fn the_real_spec_models_compile() {
    if Command::new("go").arg("version").output().is_err() {
        eprintln!("SKIPPED: go toolchain not available; CI runs this gate");
        return;
    }
    let dir = std::env::temp_dir().join(format!("gantry-go-models-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    write_all(&dir, &generate());

    let build = Command::new("go")
        .args(["build", "./..."])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        build.status.success(),
        "go build failed (VR-1.1):\n{}",
        String::from_utf8_lossy(&build.stderr)
    );

    let vet = Command::new("go")
        .args(["vet", "./..."])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        vet.status.success(),
        "go vet failed (VR-1.1):\n{}",
        String::from_utf8_lossy(&vet.stderr)
    );

    let fmt = Command::new("gofmt").arg("-l").arg(&dir).output().unwrap();
    assert!(
        fmt.status.success() && fmt.stdout.is_empty(),
        "gofmt wants changes (G-17) in:\n{}",
        String::from_utf8_lossy(&fmt.stdout)
    );

    // The generated round-trip tests must pass (FR-7.8, VR-4). The
    // serialization and schemas packages need no runtime, so they run
    // against the stubs.
    let test = Command::new("go")
        .args(["test", "./serialization/...", "./schemas/..."])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        test.status.success(),
        "generated go tests failed (FR-7.8, VR-4):\n{}\n{}",
        String::from_utf8_lossy(&test.stdout),
        String::from_utf8_lossy(&test.stderr)
    );
}

/// FR-5.2/TR-Go.7: the generated SDK must compile against the real
/// hand-written runtime, not only the stubs — proving the runtime
/// satisfies the contract signatures the managers call.
#[test]
fn the_generated_sdk_compiles_against_the_real_runtime() {
    if Command::new("go").arg("version").output().is_err() {
        eprintln!("SKIPPED: go toolchain not available; CI runs this gate");
        return;
    }
    let dir = std::env::temp_dir().join(format!("gantry-go-runtime-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    write_all(&dir, &generate());

    // Replace the generated stub package with the real runtime files.
    let runtime_dir =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../runtimes/go/gantryruntime");
    let target = dir.join("gantryruntime");
    let _ = std::fs::remove_file(target.join("runtime.go")); // the stub
    for entry in std::fs::read_dir(&runtime_dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "go") {
            let name = path.file_name().unwrap();
            std::fs::copy(&path, target.join(name)).unwrap();
        }
    }

    // A smoke main proving the public API composes end to end: construct
    // the client from a token source and reach a manager method.
    let smoke = "package main\n\n\
        import (\n\
        \t\"context\"\n\
        \t\"fmt\"\n\n\
        \t\"github.com/unofficialbox/box-open-go-sdk/auth\"\n\
        \t\"github.com/unofficialbox/box-open-go-sdk/client\"\n\
        )\n\n\
        func main() {\n\
        \tc := client.NewClient(auth.DeveloperToken(\"dev-token\"))\n\
        \tif false {\n\
        \t\t_, _ = c.Files.Get(context.Background(), \"123\", nil)\n\
        \t}\n\
        \tfmt.Println(c)\n\
        }\n";
    std::fs::create_dir_all(dir.join("cmd/smoke")).unwrap();
    std::fs::write(dir.join("cmd/smoke/main.go"), smoke).unwrap();

    // The README Quickstart must itself compile against the real SDK (FR-7.7):
    // extract its ```go block and build it, so the landing-page example can
    // never drift from the generated surface (the class of bug that shipped a
    // `user.ID` typo). `go build ./...` below compiles it with everything else.
    let readme = std::fs::read_to_string(dir.join("README.md")).unwrap();
    let example = {
        let open = "```go\n";
        let start = readme.find(open).expect("README has a go example") + open.len();
        let len = readme[start..].find("\n```").expect("the go block closes");
        &readme[start..start + len]
    };
    std::fs::create_dir_all(dir.join("cmd/readme")).unwrap();
    std::fs::write(dir.join("cmd/readme/main.go"), example).unwrap();

    let build = Command::new("go")
        .args(["build", "./..."])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        build.status.success(),
        "generated SDK does not compile against the real runtime (contract drift, FR-5.2):\n{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let vet = Command::new("go")
        .args(["vet", "./..."])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        vet.status.success(),
        "go vet failed against the real runtime:\n{}",
        String::from_utf8_lossy(&vet.stderr)
    );
}

/// D-192: the shipped tree must carry the real runtime, never the
/// compile-only contract stub. Every other gate here proves the output
/// *compiles* — which the stub does, while panicking on every call. This is
/// the one that proves it *works*.
#[test]
fn no_generated_file_ships_the_runtime_stub() {
    let files = generate();
    let findings = gantry_verify::shipping::stub_findings(
        files.iter().map(|f| (f.path.as_str(), f.content.as_str())),
    );
    assert!(
        findings.is_empty(),
        "generated SDK ships runtime stubs instead of the vendored runtime: {findings:#?}"
    );
    // The runtime is actually present, so an empty result can't mean
    // "nothing was emitted".
    assert!(
        files.iter().any(|f| f.path == "gantryruntime/runtime.go"),
        "expected the vendored runtime at gantryruntime/runtime.go"
    );
}
