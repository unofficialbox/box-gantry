//! Rust stub rendering (FR-5.3).
//!
//! Renders the contract to a compilable Rust module so generated SDK code
//! compile-verifies against it without the real runtime (G-1). The stub and
//! the declared surface are rendered from the same data, so they cannot drift
//! (FR-5.2). Error shape and async-ness come from the capability manifest's
//! axes, never a language name (FR-4.2): `ErrorModel::Result` →
//! `Result<T, Error>`, `AsyncModel::Async` → the network entry points
//! (`takes_context`) become `async fn` — Rust threads cancellation through the
//! future itself, so no context parameter is emitted.

use std::fmt::Write as _;

use gantry_manifest::{AsyncModel, CapabilityManifest, ErrorModel};

use crate::{ContractFn, ContractType, Receiver, RuntimeContract};

/// Render the compilable Rust stub module (`runtime.rs`) for a contract.
///
/// Deterministic (FR-6.2) and rustfmt-clean by construction (G-17); every stub
/// `unimplemented!()`s loudly (NF-1 — a stub returning a default would hide
/// missing runtime wiring).
pub fn rust_stubs(contract: &RuntimeContract, manifest: &CapabilityManifest) -> String {
    assert_eq!(
        manifest.error_model,
        ErrorModel::Result,
        "the Rust stub renderer implements the Result axis"
    );
    assert_eq!(
        manifest.async_model,
        AsyncModel::Async,
        "the Rust stub renderer implements the async axis"
    );

    let mut out = String::new();
    out.push_str(
        "// Code generated by gantry-contract — do not edit.\n\
         //\n\
         // Compilable stubs for the hand-written runtime surface (FR-5.3).\n\
         // Generated SDK code compile-verifies against this module; the real\n\
         // runtime implements the same contract.\n\
         #![allow(dead_code, unused_variables, clippy::all)]\n\n\
         /// The runtime-owned HTTP request envelope.\n\
         pub struct Request;\n\n\
         /// The runtime-owned HTTP response envelope.\n\
         pub struct Response;\n\n\
         /// A streaming body (buffered on platforms whose manifest says so).\n\
         pub struct Stream;\n\n\
         impl Stream {\n\
         \x20   /// An empty stream (e.g. an absent multipart file part).\n\
         \x20   pub fn empty() -> Stream {\n\
         \x20       unimplemented!(\"gantryruntime stub: Stream::empty is not wired to a real runtime\")\n\
         \x20   }\n\
         }\n\n\
         /// The configured authentication flow (developer token, CCG, OAuth, JWT).\n\
         pub struct Auth;\n\n\
         /// A runtime error: a failed request, auth acquisition, or body decode.\n\
         #[derive(Debug)]\n\
         pub struct Error(String);\n\n\
         impl std::fmt::Display for Error {\n\
         \x20   fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n\
         \x20       write!(f, \"{}\", self.0)\n\
         \x20   }\n\
         }\n\n\
         impl std::error::Error for Error {}\n\n\
         impl From<serde_json::Error> for Error {\n\
         \x20   fn from(err: serde_json::Error) -> Self {\n\
         \x20       Error(err.to_string())\n\
         \x20   }\n\
         }\n\n\
         /// The runtime session: auth, base URLs, HTTP client, retry policy.\n\
         /// Session-receiver contract functions are its methods.\n\
         pub struct Client;\n\n",
    );

    // Session functions become methods on `Client`, alongside the hand-declared
    // constructor; free functions are module-level (FR-5.1 receiver axis).
    out.push_str("impl Client {\n");
    out.push_str(
        "    /// Build a runtime session for an authentication flow.\n\
         \x20   pub fn new(auth: Auth) -> Client {\n\
         \x20       unimplemented!(\"gantryruntime stub: Client::new is not wired to a real runtime\")\n\
         \x20   }\n\n",
    );
    for function in contract.functions {
        if function.receiver == Receiver::Session {
            render_method(&mut out, function);
        }
    }
    // Drop the trailing blank line the last method left before closing `impl`.
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n\n");

    for function in contract.functions {
        if function.receiver == Receiver::Free {
            render_free_fn(&mut out, function);
        }
    }

    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// A session function → an inherent method on `Client` (4-space indent).
fn render_method(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "    /// {}", function.behavior);
    emit_signature(out, "    ", function, true);
    let _ = writeln!(
        out,
        "        unimplemented!(\"gantryruntime stub: {} is not wired to a real runtime\")",
        function.name
    );
    out.push_str("    }\n\n");
}

/// A free function → a module-level `pub fn`.
fn render_free_fn(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "/// {}", function.behavior);
    emit_signature(out, "", function, false);
    let _ = writeln!(
        out,
        "    unimplemented!(\"gantryruntime stub: {} is not wired to a real runtime\")",
        function.name
    );
    out.push_str("}\n\n");
}

/// Emit a `pub [async] fn …(…) -> … {` signature at `indent`, wrapping one
/// parameter per line exactly as rustfmt does when the single line would
/// overflow 100 columns.
fn emit_signature(out: &mut String, indent: &str, function: &ContractFn, method: bool) {
    let keyword = if function.takes_context {
        "async fn"
    } else {
        "fn"
    };
    let mut params: Vec<String> = Vec::new();
    if method {
        params.push("&self".to_string());
    }
    for (name, ty) in function.params {
        params.push(format!("{name}: {}", param_type(*ty)));
    }
    let ret = return_type(function);
    let single = format!(
        "{indent}pub {keyword} {}({}) -> {ret} {{",
        function.name,
        params.join(", ")
    );
    if single.len() <= 100 {
        let _ = writeln!(out, "{single}");
        return;
    }
    let _ = writeln!(out, "{indent}pub {keyword} {}(", function.name);
    for param in &params {
        let _ = writeln!(out, "{indent}    {param},");
    }
    let _ = writeln!(out, "{indent}) -> {ret} {{");
}

/// The return type, wrapped in `Result` when the function is fallible.
fn return_type(function: &ContractFn) -> String {
    let inner = function.ret.map_or_else(|| "()".to_string(), owned_type);
    if function.fallible {
        format!("Result<{inner}, Error>")
    } else {
        inner
    }
}

/// A borrowed parameter type (idiomatic: `&str`/`&[u8]`/`&Response`).
fn param_type(ty: ContractType) -> &'static str {
    match ty {
        ContractType::Context => "()", // never emitted; context is async in Rust
        ContractType::String => "&str",
        ContractType::Bytes => "&[u8]",
        ContractType::Bool => "bool",
        ContractType::Int64 => "i64",
        ContractType::Json => "&serde_json::Value",
        ContractType::Request => "Request",
        ContractType::Response => "&Response",
        ContractType::Stream => "Stream",
    }
}

/// An owned return type.
fn owned_type(ty: ContractType) -> String {
    match ty {
        ContractType::Context => "()".to_string(),
        ContractType::String => "String".to_string(),
        ContractType::Bytes => "Vec<u8>".to_string(),
        ContractType::Bool => "bool".to_string(),
        ContractType::Int64 => "i64".to_string(),
        ContractType::Json => "serde_json::Value".to_string(),
        ContractType::Request => "Request".to_string(),
        ContractType::Response => "Response".to_string(),
        ContractType::Stream => "Stream".to_string(),
    }
}
