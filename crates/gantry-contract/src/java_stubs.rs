//! Java stub rendering (FR-5.3).
//!
//! Renders the contract to a compilable Java source file so generated SDK code
//! compile-verifies against it without the real runtime (G-1). The stub and the
//! declared surface are rendered from the same data, so they cannot drift
//! (FR-5.2). Error shape and async-ness come from the capability manifest's axes,
//! never a language name (FR-4.2): `ErrorModel::Exceptions` → a failure throws
//! (an unchecked `BoxApiException`), so `fallible` never widens a return type;
//! `AsyncModel::Sync` → the network entry points are ordinary **blocking**
//! methods (no `Future`/async). Java's blocking model carries no
//! context/cancellation object — concurrency is the caller's business over
//! virtual threads (the D-164 manifest note) — so, like TypeScript, no context
//! parameter is emitted.
//!
//! Java is one public type per file, so the whole surface is emitted as one
//! `Runtime` class with the envelope types (`Request`/`Response`/`Stream`/
//! `Auth`/`BoxApiException`) and the runtime `Session` as nested classes, and
//! the free contract functions as its `static` methods. Generated code refers to
//! them as `dev.unofficialbox.runtime.Runtime.Session` / `Runtime.withQuery(...)`.

use std::fmt::Write as _;

use gantry_manifest::{AsyncModel, CapabilityManifest, ErrorModel};

use crate::{ContractFn, ContractType, Receiver, RuntimeContract};

/// Render the compilable Java stub file (`Runtime.java`) for a contract.
/// Deterministic (FR-6.2); every stub throws loudly (NF-1 — a stub returning a
/// default would hide missing runtime wiring).
pub fn java_stubs(contract: &RuntimeContract, manifest: &CapabilityManifest) -> String {
    assert_eq!(
        manifest.error_model,
        ErrorModel::Exceptions,
        "the Java stub renderer implements the Exceptions axis"
    );
    assert_eq!(
        manifest.async_model,
        AsyncModel::Sync,
        "the Java stub renderer implements the sync (blocking) axis"
    );

    let mut out = String::from(
        "// Code generated by gantry-contract — do not edit.\n\
         //\n\
         // Compilable stubs for the hand-written runtime surface (FR-5.3).\n\
         // Generated SDK code compiles against this class; the real runtime\n\
         // implements the same contract.\n\
         package dev.unofficialbox.runtime;\n\
         \n\
         /** The hand-written runtime surface (FR-5). */\n\
         public final class Runtime {\n\
         \x20   private Runtime() {}\n\
         \n\
         \x20   /** The runtime-owned HTTP request envelope. */\n\
         \x20   public static final class Request {}\n\
         \n\
         \x20   /** The runtime-owned HTTP response envelope. */\n\
         \x20   public static final class Response {}\n\
         \n\
         \x20   /** A streaming body (buffered on platforms whose manifest says so). */\n\
         \x20   public static final class Stream {\n\
         \x20       /** An empty stream (e.g. an absent multipart file part). */\n\
         \x20       public static Stream empty() {\n\
         \x20           throw new UnsupportedOperationException(\
         \"gantryruntime stub: Stream.empty is not wired to a real runtime\");\n\
         \x20       }\n\
         \n\
         \x20       /** A stream over in-memory bytes (an octet-stream request body). */\n\
         \x20       public static Stream fromBytes(byte[] data) {\n\
         \x20           throw new UnsupportedOperationException(\
         \"gantryruntime stub: Stream.fromBytes is not wired to a real runtime\");\n\
         \x20       }\n\
         \x20   }\n\
         \n\
         \x20   /** The configured authentication flow (developer token, CCG, OAuth, JWT). */\n\
         \x20   public static final class Auth {}\n\
         \n\
         \x20   /** A runtime error: a failed request, auth acquisition, or body decode. */\n\
         \x20   public static final class BoxApiException extends RuntimeException {\n\
         \x20       private static final long serialVersionUID = 1L;\n\
         \n\
         \x20       public BoxApiException(String message) {\n\
         \x20           super(message);\n\
         \x20       }\n\
         \x20   }\n\
         \n\
         \x20   /**\n\
         \x20    * The runtime session: auth, base URLs, HTTP client, retry policy.\n\
         \x20    * Session-receiver contract functions are its methods.\n\
         \x20    */\n\
         \x20   public static final class Session {\n\
         \x20       /** Build a runtime session for an authentication flow. */\n\
         \x20       public Session(Auth auth) {\n\
         \x20           throw new UnsupportedOperationException(\
         \"gantryruntime stub: Session is not wired to a real runtime\");\n\
         \x20       }\n\
         \n",
    );

    for function in contract.functions {
        if function.receiver == Receiver::Session {
            render_method(&mut out, function);
        }
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n    }\n\n");

    for function in contract.functions {
        if function.receiver == Receiver::Free {
            render_free_fn(&mut out, function);
        }
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n");
    out
}

/// A session function → a method on `Session` (8-space indent, nested twice).
fn render_method(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "        /** {} */", function.behavior);
    let _ = writeln!(
        out,
        "        public {} {}({}) {{",
        return_type(function),
        method_name(function.name),
        params(function),
    );
    let _ = writeln!(
        out,
        "            throw new UnsupportedOperationException(\
         \"gantryruntime stub: {} is not wired to a real runtime\");",
        function.name
    );
    out.push_str("        }\n\n");
}

/// A free function → a `static` method on `Runtime` (4-space indent).
fn render_free_fn(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "    /** {} */", function.behavior);
    let _ = writeln!(
        out,
        "    public static {} {}({}) {{",
        return_type(function),
        method_name(function.name),
        params(function),
    );
    let _ = writeln!(
        out,
        "        throw new UnsupportedOperationException(\
         \"gantryruntime stub: {} is not wired to a real runtime\");",
        function.name
    );
    out.push_str("    }\n\n");
}

/// The parameter list, `Type name` comma-joined. The context carrier is not
/// emitted: Java's blocking model has no context object (cancellation is the
/// caller's business over virtual threads), the same choice TypeScript makes.
fn params(function: &ContractFn) -> String {
    function
        .params
        .iter()
        .filter(|(_, ty)| *ty != ContractType::Context)
        .map(|(name, ty)| format!("{} {}", java_type(*ty), camel(name)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The return type — the value type directly. In the exceptions model a failure
/// throws rather than widening the type, so `fallible` does not change it; the
/// sync model means no `Future` wrapper either.
fn return_type(function: &ContractFn) -> String {
    function.ret.map_or_else(|| "void".to_string(), java_type)
}

fn method_name(name: &str) -> String {
    camel(name)
}

/// A contract type → its Java spelling. Envelope types are the nested classes,
/// so they need no qualification inside `Runtime`.
fn java_type(ty: ContractType) -> String {
    match ty {
        ContractType::Context => "void".to_string(), // never emitted
        ContractType::String => "String".to_string(),
        ContractType::Bytes => "byte[]".to_string(),
        ContractType::Bool => "boolean".to_string(),
        ContractType::Int64 => "long".to_string(),
        ContractType::Json => "Object".to_string(),
        ContractType::Request => "Request".to_string(),
        ContractType::Response => "Response".to_string(),
        ContractType::Stream => "Stream".to_string(),
    }
}

/// `snake_case` → `camelCase` (the Java casing for the canonical names).
fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper = false;
    for ch in name.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}
