//! TypeScript stub rendering (FR-5.3).
//!
//! Renders the contract to a type-checkable TypeScript module so generated SDK
//! code compile-verifies against it without the real runtime (G-1). The stub
//! and the declared surface are rendered from the same data, so they cannot
//! drift (FR-5.2). Error shape and async-ness come from the capability
//! manifest's axes, never a language name (FR-4.2): `ErrorModel::Exceptions` →
//! functions throw (a `BoxApiError` subclass), `AsyncModel::Async` → the
//! network entry points (`takes_context`) return `Promise<T>`. TypeScript
//! threads cancellation through the platform (`AbortSignal`), so no context
//! parameter is emitted.

use std::fmt::Write as _;

use gantry_manifest::{AsyncModel, CapabilityManifest, ErrorModel};

use crate::{ContractFn, ContractType, Receiver, RuntimeContract};

/// Render the type-checkable TypeScript stub module (`runtime.ts`) for a
/// contract. Deterministic (FR-6.2); every stub `throw`s loudly (NF-1 — a stub
/// returning a default would hide missing runtime wiring).
pub fn typescript_stubs(contract: &RuntimeContract, manifest: &CapabilityManifest) -> String {
    assert_eq!(
        manifest.error_model,
        ErrorModel::Exceptions,
        "the TypeScript stub renderer implements the Exceptions axis"
    );
    assert_eq!(
        manifest.async_model,
        AsyncModel::Async,
        "the TypeScript stub renderer implements the async axis"
    );

    let mut out = String::from(
        "// Code generated by gantry-contract — do not edit.\n\
         //\n\
         // Type-checkable stubs for the hand-written runtime surface (FR-5.3).\n\
         // Generated SDK code type-checks against this module; the real runtime\n\
         // implements the same contract.\n\
         /* eslint-disable */\n\n\
         /** The runtime-owned HTTP request envelope. */\n\
         export class Request {}\n\n\
         /** The runtime-owned HTTP response envelope. */\n\
         export class Response {}\n\n\
         /** A streaming body (buffered on platforms whose manifest says so). */\n\
         export class Stream {\n\
         \x20 /** An empty stream (e.g. an absent multipart file part). */\n\
         \x20 static empty(): Stream {\n\
         \x20   throw new Error('gantryruntime stub: Stream.empty is not wired to a real runtime');\n\
         \x20 }\n\
         }\n\n\
         /** The configured authentication flow (developer token, CCG, OAuth, JWT). */\n\
         export class Auth {}\n\n\
         /** A runtime error: a failed request, auth acquisition, or body decode. */\n\
         export class BoxApiError extends Error {}\n\n\
         /**\n\
         \x20* The runtime session: auth, base URLs, HTTP client, retry policy.\n\
         \x20* Session-receiver contract functions are its methods.\n\
         \x20*/\n\
         export class Client {\n\
         \x20 /** Build a runtime session for an authentication flow. */\n\
         \x20 constructor(auth: Auth) {\n\
         \x20   throw new Error('gantryruntime stub: Client is not wired to a real runtime');\n\
         \x20 }\n\n",
    );

    for function in contract.functions {
        if function.receiver == Receiver::Session {
            render_method(&mut out, function);
        }
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n\n");

    for function in contract.functions {
        if function.receiver == Receiver::Free {
            render_free_fn(&mut out, function);
        }
    }

    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// A session function → a method on `Client` (2-space indent).
fn render_method(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "  /** {} */", function.behavior);
    let _ = writeln!(
        out,
        "  {}{}({}): {} {{",
        if function.takes_context { "async " } else { "" },
        method_name(function.name),
        params(function),
        return_type(function),
    );
    let _ = writeln!(
        out,
        "    throw new Error('gantryruntime stub: {} is not wired to a real runtime');",
        function.name
    );
    out.push_str("  }\n\n");
}

/// A free function → an exported module-level function.
fn render_free_fn(out: &mut String, function: &ContractFn) {
    let _ = writeln!(out, "/** {} */", function.behavior);
    let _ = writeln!(
        out,
        "export function {}({}): {} {{",
        method_name(function.name),
        params(function),
        return_type(function),
    );
    let _ = writeln!(
        out,
        "  throw new Error('gantryruntime stub: {} is not wired to a real runtime');",
        function.name
    );
    out.push_str("}\n\n");
}

/// The parameter list, `name: Type` comma-joined. The context carrier is
/// rendered as TypeScript's cancellation idiom instead of a context parameter:
/// the async (network) entry points take a trailing optional `signal?:
/// AbortSignal` — TypeScript cancels via `AbortSignal`, not by dropping a
/// future the way Rust does.
fn params(function: &ContractFn) -> String {
    let mut parts: Vec<String> = function
        .params
        .iter()
        .filter(|(_, ty)| *ty != ContractType::Context)
        .map(|(name, ty)| format!("{}: {}", camel(name), ts_type(*ty)))
        .collect();
    if function.takes_context {
        parts.push("signal?: AbortSignal".to_string());
    }
    parts.join(", ")
}

/// The return type: `Promise<T>` for the async (network) entry points, `T`
/// otherwise. In the exceptions model a failure throws rather than widening the
/// type, so `fallible` does not change the return type.
fn return_type(function: &ContractFn) -> String {
    let inner = function.ret.map_or_else(|| "void".to_string(), ts_type);
    if function.takes_context {
        format!("Promise<{inner}>")
    } else {
        inner
    }
}

fn method_name(name: &str) -> String {
    camel(name)
}

/// A contract type → its TypeScript spelling.
fn ts_type(ty: ContractType) -> String {
    match ty {
        ContractType::Context => "never".to_string(), // never emitted
        ContractType::String => "string".to_string(),
        ContractType::Bytes => "Uint8Array".to_string(),
        ContractType::Bool => "boolean".to_string(),
        ContractType::Int64 => "number".to_string(),
        ContractType::Json => "unknown".to_string(),
        ContractType::Request => "Request".to_string(),
        ContractType::Response => "Response".to_string(),
        ContractType::Stream => "Stream".to_string(),
    }
}

/// `snake_case` → `camelCase` (the TypeScript casing for the canonical names).
fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper = false;
    for ch in name.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}
